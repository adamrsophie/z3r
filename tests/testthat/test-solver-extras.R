test_that("proofs of unsatisfiability", {
  ctx <- z3_context(proof = TRUE)
  p <- z3_bool(ctx, "p")
  q <- z3_bool(ctx, "q")
  s <- z3_solver(ctx)
  z3_add(s, z3_implies(p, q), p, !q)
  expect_error(z3_proof(s), "only available")
  expect_identical(z3_check(s), "unsat")
  pr <- z3_proof(s)
  expect_s3_class(pr, "z3_expr")
  expect_match(format(pr), "asserted")
  z3_add(s, TRUE)
  expect_error(z3_proof(s), "only available")
})

test_that("consequences of assumptions", {
  ctx <- z3_context()
  p <- z3_bool(ctx, "p")
  q <- z3_bool(ctx, "q")
  r <- z3_bool(ctx, "r")
  s <- z3_solver(ctx)
  z3_add(s, z3_implies(p, q), z3_implies(q, r))
  res <- z3_consequences(s, list(p), list(q, r))
  expect_identical(res$status, "sat")
  expect_length(res$consequences, 2L)
  txt <- vapply(res$consequences, format, "")
  expect_true(all(grepl("=> p", txt)))
})

test_that("cubes, units and the trail", {
  ctx <- z3_context()
  p <- z3_bools(ctx, c("a", "b"))
  s <- z3_solver(ctx)
  z3_add(s, p$a | p$b)
  cube <- z3_cube(s, list(p$a, p$b))
  expect_type(cube, "list")
  s2 <- z3_solver(ctx, simple = TRUE)
  z3_add(s2, p$a, p$a | p$b)
  expect_identical(z3_check(s2), "sat")
  tr <- z3_trail(s2)
  expect_named(tr, c("literals", "levels"))
  expect_length(tr$levels, length(tr$literals))
  expect_type(z3_units(s2), "list")
  expect_type(z3_non_units(s2), "list")
  expect_error(z3_solver(ctx, logic = "QF_LIA", simple = TRUE), "cannot also")
})

test_that("help, DIMACS and solver hints", {
  ctx <- z3_context()
  p <- z3_bools(ctx, c("a", "b"))
  s <- z3_solver(ctx)
  expect_match(z3_help(s), "timeout")
  z3_add(s, p$a | p$b, !p$a)
  d <- z3_to_dimacs(s)
  expect_match(d, "^p cnf 2 2")
  g <- z3_goal(ctx)
  z3_add(g, p$a | !p$b)
  expect_match(z3_to_dimacs(g), "p cnf")
  expect_match(z3_help(z3_optimize(ctx)), "priority")
  expect_match(z3_help(z3_tactic(ctx, "simplify")), "som")
  skip_if_not(z3_version_at_least("4.13.2"))
  x <- z3_int(ctx, "x")
  s2 <- z3_solver(ctx, simple = TRUE)
  z3_add(s2, x > 0)
  z3_set_initial_value(s2, x, 42)
  expect_identical(z3_check(s2), "sat")
  o <- z3_optimize(ctx)
  z3_add(o, x > 0)
  expect_invisible(z3_set_initial_value(o, x, 3))
})

test_that("congruence classes and solving for variables", {
  skip_if_not(z3_version_at_least("4.12.0"))
  ctx <- z3_context()
  a <- z3_int(ctx, "a")
  b <- z3_int(ctx, "b")
  s <- z3_solver(ctx)
  z3_add(s, a == b)
  expect_error(z3_congruence_root(s, a), "only available")
  z3_check(s)
  expect_s3_class(z3_congruence_root(s, a), "z3_expr")
  expect_s3_class(z3_congruence_next(s, a), "z3_expr")
  skip_if_not(z3_version_at_least("4.14.0"))
  res <- z3_solve_for(s, list(a))
  expect_named(res, c("vars", "terms", "guards"))
  expect_length(res$vars, length(res$terms))
})

test_that("z3_solve_for() reports which variables it solved", {
  skip_if_not(z3_version_at_least("4.14.0"))
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  z <- z3_int(ctx, "z")
  s <- z3_solver(ctx, simple = TRUE)
  z3_add(s, x == y + 1)
  z3_check(s)
  res <- z3_solve_for(s, list(z, x, y))
  expect_length(res$vars, length(res$terms))
  expect_true(length(res$vars) >= 1L)
  # Each solved variable equals its term under the guards.
  for (i in seq_along(res$vars)) {
    chk <- z3_solver(ctx)
    z3_add(chk, x == y + 1, res$vars[[i]] != res$terms[[i]])
    for (g in res$guards) z3_add(chk, g)
    expect_identical(z3_check(chk), "unsat")
  }
})

test_that("models can be built by hand", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  m <- z3_model(ctx)
  z3_model_set(m, x, 5)
  z3_model_set(m, r, 2)
  z3_model_set_function(m, f, list(list(args = list(5), value = 50)), 0)
  expect_identical(z3_value(z3_eval(m, f(x) + f(1))), 50)
  expect_identical(z3_value(z3_eval(m, r / 4)), 0.5)
  expect_true(z3_model_has(m, x))
  expect_true(z3_model_has(m, f))
  expect_false(z3_model_has(m, z3_int(ctx, "unused")))
  expect_error(z3_model_set(m, x + 1, 2), "only constants")
  expect_error(z3_model_set(m, x, TRUE), "wrong sort")
})

test_that("sort universes and as-array values", {
  ctx <- z3_context()
  U <- z3_uninterpreted_sort(ctx, "U")
  a <- z3_const(ctx, "a", U)
  b <- z3_const(ctx, "b", U)
  s <- z3_solver(ctx)
  z3_add(s, a != b)
  z3_check(s)
  u <- z3_model_universes(z3_model(s))
  expect_named(u, "U")
  expect_length(u$U, 2L)
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  expect_s3_class(z3_as_array_function(z3_as_array(f)), "z3_func_decl")
  expect_null(z3_as_array_function(z3_int(ctx, "x")))
})

test_that("function interpretations are sort checked before the model changes", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  R <- z3_real_sort(ctx)
  f <- z3_function(ctx, "f", I, I)
  g <- z3_function(ctx, "g", I, R)
  m <- z3_model(ctx)
  z3_model_set_function(m, f, list(list(args = list(1), value = 10)), 0)
  expect_error(z3_model_set_function(m, f, list(), TRUE), "wrong sort")
  expect_error(z3_model_set_function(m, f, list(list(args = list(TRUE), value = 1)), 0), "wrong sort")
  expect_error(z3_model_set_function(m, f, list(list(args = list(1), value = 2), list(args = list(2), value = FALSE)), 0),
               "wrong sort")
  # The earlier interpretation survives the failed calls.
  expect_identical(z3_value(z3_eval(m, f(1))), 10)
  z3_model_set_function(m, g, list(list(args = list(1), value = 2L)), 0L)
  expect_identical(z3_value(z3_eval(m, g(1))), 2)
  k <- z3_function(ctx, "k", list(), I)
  expect_error(z3_model_set_function(m, k, list(), 1), "no arguments")
  expect_identical(z3_value(z3_eval(m, g(1) / 4)), 0.5)
})
