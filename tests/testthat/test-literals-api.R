test_that("machine integers become numerals of the hinted sort", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  expect_identical(format(x + 5L), "(+ x 5)")
  expect_identical(format(x + -5L), "(+ x (- 5))")
  expect_identical(format(r + 3L), "(+ r 3.0)")
  expect_identical(format(z3_int_val(ctx, 2^40)), "1099511627776")
  expect_identical(format(z3_int_val(ctx, -2^40)), "(- 1099511627776)")
  expect_identical(format(z3_int_val(ctx, -2^31)), "(- 2147483648)")
  expect_identical(format(r + z3_int_val(ctx, 2^40)), "(+ r 1099511627776.0)")
  expect_identical(format(r + z3_int_val(ctx, "123456789012345678901234567890")),
                   "(+ r 123456789012345678901234567890.0)")
  expect_identical(z3_value(z3_bv_val(ctx, -1, 8)), 255)
  expect_identical(z3_value(z3_bv_val(ctx, 2^32, 40)), 2^32)
  expect_identical(z3_value(z3_bv_val(ctx, -2^39, 40)), 2^39)
  expect_error(z3_bv_val(ctx, 2^40, 40), "does not fit")
  expect_error(z3_bv_val(ctx, -2^39 - 1, 40), "does not fit")
  expect_identical(z3_value(z3_bv_val(ctx, -1, 64), signed = TRUE), -1)
  if (requireNamespace("bit64", quietly = TRUE)) {
    v <- z3_val(ctx, bit64::as.integer64("-9007199254740993"), z3_int_sort(ctx))
    expect_identical(format(v), "(- 9007199254740993)")
  }
})

test_that("fractions from a numerator and a denominator are exact", {
  ctx <- z3_context()
  expect_identical(format(z3_real_val(ctx, 1, 3)), "(/ 1.0 3.0)")
  expect_identical(format(z3_real_val(ctx, 2L, 4L)), "(/ 1.0 2.0)")
  expect_identical(format(z3_real_val(ctx, 1, -3)), "(- (/ 1.0 3.0))")
  expect_identical(format(z3_real_val(ctx, 6, 3)), "2.0")
  expect_identical(z3_value(z3_real_val(ctx, 2^40, 2^41)), 0.5)
  expect_identical(format(z3_real_val(ctx, 2^53, 3)), "(/ 9007199254740992.0 3.0)")
  if (requireNamespace("bit64", quietly = TRUE)) {
    v <- z3_real_val(ctx, bit64::as.integer64("9007199254740993"), 2)
    expect_identical(format(v), "(/ 9007199254740993.0 2.0)")
  }
  expect_error(z3_real_val(ctx, 1, 0), "denominator must not be zero")
  expect_error(z3_real_val(ctx, 0.5, 2), "whole number")
  expect_error(z3_real_val(ctx, 1, 2^54), "whole number")
  expect_error(z3_real_val(ctx, "1", 2), "whole number")
})

test_that("values are read exactly through machine integers", {
  ctx <- z3_context()
  expect_identical(z3_value(z3_int_val(ctx, -2^53)), -2^53)
  expect_identical(z3_value(z3_real_val(ctx, -3, 8)), -0.375)
  expect_identical(z3_value(z3_real_val(ctx, 1, 2^52)), 2^-52)
  expect_identical(z3_value(z3_real_val(ctx, "1/4611686018427387904")), 2^-62)
  expect_identical(z3_value(z3_real_val(ctx, 5L)), 5)
  expect_identical(z3_value(z3_bv_val(ctx, 2^32 - 1, 32)), 2^32 - 1)
  expect_identical(z3_value(z3_bv_val(ctx, 2^40, 48)), 2^40)
  # 2^53 + 1 is not a double; rounding is only on request.
  expect_identical(z3_value(z3_int_val(ctx, "9007199254740993"), exact = FALSE), 2^53)
  expect_equal(z3_value(z3_real_val(ctx, 1, 3), exact = FALSE), 1 / 3)
  if (requireNamespace("gmp", quietly = TRUE)) {
    expect_identical(as.character(z3_value(z3_real_val(ctx, -1, 3))), "-1/3")
  }
  expect_identical(as.integer(z3_int_val(ctx, -2147483647)), -2147483647L)
  expect_identical(as.integer(z3_bv_val(ctx, 200, 8)), 200L)
  expect_identical(as.integer(z3_real_val(ctx, 6, 3)), 2L)
  expect_error(as.integer(z3_int_val(ctx, -2^31)), "integer range")
  expect_error(as.integer(z3_real_val(ctx, 1, 2)), "integer range")
  expect_error(as.integer(z3_int(ctx, "x")), "symbolic")
})

test_that("whole-number names make integer symbols", {
  ctx <- z3_context()
  k <- z3_int(ctx, 7L)
  expect_identical(format(k), "k!7")
  expect_true(z3_identical(k, z3_int(ctx, 7)))
  expect_false(z3_identical(k, z3_int(ctx, "k!7")))
  expect_true(z3_is_const(k))
  expect_false(z3_is_const(k + 1))
  expect_false(z3_is_const(z3_int_val(ctx, 1)))
  expect_error(z3_int(ctx, -1), "0 to 2\\^30 - 1")
  expect_error(z3_int(ctx, 2^30), "0 to 2\\^30 - 1")
  expect_error(z3_int(ctx, 1.5), "whole number")
  expect_error(z3_int(ctx, factor("a")), "single non-missing string")
})

test_that("abs uses Z3's abs where available", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  expected <- if (z3_version_at_least("4.13.2")) "(abs x)" else "(ite (< x 0) (- x) x)"
  expect_identical(format(abs(x)), expected)
  expect_identical(z3_value(z3_simplify(abs(z3_real_val(ctx, -3, 4)))), 0.75)
  expect_identical(z3_value(z3_simplify(abs(z3_int_val(ctx, -5)))), 5)
  expect_identical(check_status(ctx, abs(r) < 0), "unsat")
  expect_identical(check_status(ctx, abs(x) == 3, x < 0, x != -3), "unsat")
})

test_that("strings with SMT-LIB escapes and raw bytes", {
  ctx <- z3_context()
  expect_identical(z3_value(z3_string_val(ctx, "a\\u{42}c", escaped = TRUE)), "aBc")
  expect_identical(z3_value(z3_string_val(ctx, "a\\u{42}c")), "a\\u{42}c")
  expect_identical(z3_value(z3_string_val(ctx, "\u00e9\\u{e9}", escaped = TRUE)), "\u00e9\u00e9")
  expect_identical(z3_string_escaped(z3_string_val(ctx, "caf\u00e9\n")), "caf\\u{e9}\\u{a}")
  x <- z3_string_val(ctx, "x\\u{0}y", escaped = TRUE)
  expect_error(z3_value(x), "U\\+0000")
  expect_identical(z3_string_escaped(x), "x\\u{0}y")
  expect_true(z3_identical(z3_string_val(ctx, z3_string_escaped(x), escaped = TRUE), x))
  bytes <- as.raw(0:255)
  b <- z3_string_val(ctx, bytes)
  expect_identical(z3_value(z3_simplify(z3_length(b))), 256)
  expect_identical(z3_string_bytes(b), bytes)
  expect_identical(z3_string_bytes(x), as.raw(c(0x78, 0, 0x79)))
  expect_identical(z3_string_bytes(z3_string_val(ctx, "\\u")), charToRaw("\\u"))
  expect_identical(z3_string_bytes(z3_string_val(ctx, raw(0))), raw(0))
  expect_error(z3_string_bytes(z3_string_val(ctx, "\u0100")), "U\\+0100")
  expect_error(z3_string_escaped(z3_string(ctx, "s")), "string value")
  expect_error(z3_string_bytes(z3_int_val(ctx, 1)), "string value")
  expect_error(z3_string_escaped(1), "z3_expr")
  expect_error(z3_string_val(ctx, "a", escaped = NA), "TRUE or FALSE")
  expect_error(z3_string_val(ctx, 1), "raw vector")
})

test_that("sort names and sequence sort checks", {
  ctx <- z3_context()
  expect_identical(z3_sort_name(z3_int_sort(ctx)), "Int")
  expect_identical(z3_sort_name(z3_real(ctx, "r")), "Real")
  expect_identical(z3_sort_name(z3_uninterpreted_sort(ctx, "Person")), "Person")
  expect_identical(z3_sort_name(z3_uninterpreted_sort(ctx, "caf\u00e9")), "caf\u00e9")
  S <- z3_string_sort(ctx)
  expect_true(z3_sort_basis(z3_re_sort(S)) == S)
  expect_error(z3_re_sort(z3_int_sort(ctx)), "sequence sorts")
  expect_error(z3_seq_empty(z3_int_sort(ctx)), "sequence sort")
  expect_error(z3_re_full(S), "regular expression sort")
  expect_error(z3_sort_basis(z3_int_sort(ctx)), "not a sequence")
  expect_error(z3_char_to_int(z3_int(ctx, "x")), "character")
  expect_error(z3_seq_nth(z3_int(ctx, "x"), 0), "sequence")
})
