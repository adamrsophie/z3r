test_that("push and pop restore earlier states, including nested scopes", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x > 0)
  z3_push(s)
  z3_add(s, x < 10)
  z3_push(s)
  z3_add(s, x > 20)
  expect_identical(z3_num_scopes(s), 2L)
  expect_identical(z3_check(s), "unsat")
  z3_pop(s)
  expect_identical(z3_check(s), "sat")
  expect_length(z3_assertions(s), 2L)
  z3_push(s)
  z3_push(s)
  z3_add(s, x == 5)
  z3_pop(s, 3)
  expect_identical(z3_num_scopes(s), 0L)
  expect_length(z3_assertions(s), 1L)
  expect_error(z3_pop(s), "cannot pop 1 scope")
  z3_pop(s, 0)
  z3_reset(s)
  expect_length(z3_assertions(s), 0L)
  expect_identical(z3_check(s), "sat")
})

test_that("models are refused when the solver changed after checking", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  expect_error(z3_model(s), "call z3_check\\(\\) before")
  z3_add(s, x > 0)
  z3_check(s)
  m <- z3_model(s)
  z3_add(s, x > 100)
  expect_error(z3_model(s), "changed since the last z3_check")
  # The earlier model is a snapshot and still evaluates.
  expect_gt(z3_value(z3_eval(m, x)), 0)
  z3_check(s)
  expect_gt(z3_value(z3_eval(z3_model(s), x)), 100)
  z3_push(s)
  expect_error(z3_model(s), "changed")
  z3_check(s)
  z3_pop(s)
  expect_error(z3_model(s), "changed")
})

test_that("assumptions hold for one check only", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  p <- z3_bool(ctx, "p")
  s <- z3_solver(ctx)
  z3_add(s, z3_implies(p, x > 10), x < 5)
  expect_identical(z3_check(s, p), "unsat")
  expect_identical(z3_check(s), "sat")
  expect_identical(z3_check(s, !p), "sat")
  expect_identical(z3_check(s, list(p, !p)), "unsat")
  expect_error(z3_check(s, x), "Boolean")
})

test_that("solver parameters are type checked", {
  ctx <- z3_context()
  s <- z3_solver(ctx)
  expect_invisible(z3_set_params(s, timeout = 5000, random_seed = 7))
  expect_error(z3_set_params(s, bogus = 1), "unknown parameter 'bogus'")
  expect_error(z3_set_params(s, timeout = -1), "non-negative whole number")
  expect_error(z3_set_params(s, timeout = "a"), "non-negative whole number")
  expect_error(z3_set_params(s, 1000), "must be named")
  help <- z3_param_help(s)
  expect_true(all(c("timeout", "rlimit", "random_seed") %in% help$name))
  expect_named(help, c("name", "kind", "description"))
})

