test_that("round trip through SMT-LIB2 text preserves meaning", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  p <- z3_bool(ctx, "p")
  s <- z3_solver(ctx)
  z3_add(s, x > 2, x < 5, r == x / 3, z3_implies(p, x == 4))
  txt <- z3_to_smtlib(s)
  expect_match(txt, "declare-fun x \\(\\) Int")
  fs <- z3_from_smtlib(ctx, txt)
  expect_length(fs, 4L)
  for (k in seq_along(fs)) expect_true(z3_identical(fs[[k]], z3_assertions(s)[[k]]))
  ctx2 <- z3_context()
  fs2 <- z3_from_smtlib(ctx2, txt)
  s2 <- z3_solver(ctx2)
  z3_add(s2, fs2, z3_bool(ctx2, "p"))
  expect_identical(z3_check(s2), "sat")
  expect_identical(z3_value(z3_eval(z3_model(s2), z3_int(ctx2, "x"))), 4)
})

test_that("parsing into solvers, files, and errors", {
  ctx <- z3_context()
  s <- z3_solver(ctx)
  z3_add_smtlib(s, c("(declare-const a Int)", "(assert (> a 10))", "(assert (< a 12))"))
  expect_identical(z3_check(s), "sat")
  expect_identical(z3_value(z3_eval(z3_model(s), z3_int(ctx, "a"))), 11)
  f <- tempfile(fileext = ".smt2")
  on.exit(unlink(f))
  writeLines(c("(declare-const b Bool)", "(assert (and b (not b)))"), f)
  fs <- z3_read_smtlib(ctx, f)
  expect_identical(check_status(ctx, fs), "unsat")
  expect_error(z3_from_smtlib(ctx, "(assert (> q 3))"), "unknown constant")
  expect_error(z3_read_smtlib(ctx, tempfile()), "existing file")
  opt <- z3_optimize(ctx)
  z3_add_smtlib(opt, "(declare-const c Int) (assert (< c 5)) (maximize c)")
  expect_identical(z3_check(opt), "sat")
  expect_match(z3_to_smtlib(opt), "maximize")
})

test_that("benchmarks from formula lists and the command interpreter", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  b <- z3_to_smtlib(list(x > 1, y < x), logic = "QF_LIA")
  expect_match(b, "set-logic QF_LIA")
  expect_match(b, "check-sat")
  out <- z3_eval_smtlib(ctx, "(declare-const k Int) (assert (= (* 2 k) 8)) (check-sat) (get-value (k))")
  expect_identical(out, "sat\n((k 4))\n")
  expect_error(z3_to_smtlib(list()), "non-empty")
  expect_error(z3_to_smtlib(list(x + 1)), "Boolean")
})

test_that("results agree with the independent z3 executable", {
  z3 <- z3_binary()
  skip_if(z3 == "", "z3 executable not installed")
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  problems <- list(
    list(x * x + y * y == 25, x > y, y > 0),
    list(x %% 7 == 3, x %/% 7 == -2),
    list(x > 0, x < 0),
    list(z3_distinct(x, y), x * y == 6, x + y == 5)
  )
  for (p in problems) {
    s <- z3_solver(ctx)
    z3_add(s, p)
    ours <- z3_check(s)
    f <- tempfile(fileext = ".smt2")
    writeLines(c(z3_to_smtlib(s), "(check-sat)"), f)
    theirs <- system2(z3, f, stdout = TRUE)
    unlink(f)
    expect_identical(ours, theirs[[1]])
  }
})
