test_that("enumerations and lists come from Z3's dedicated constructors", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  Dir <- z3_enum_sort(ctx, "Dir", c("north", "south"))
  expect_s3_class(Dir, "z3_datatype")
  expect_named(Dir, c("sort", "north", "is_north", "south", "is_south"))
  d <- z3_const(ctx, "d", Dir$sort)
  expect_identical(check_status(ctx, d != Dir$north, d != Dir$south), "unsat")
  expect_true(z3_value(z3_simplify(Dir$is_south(Dir$south))))
  expect_true(z3_identical(z3_datatype_of(Dir$sort)$north, Dir$north))
  expect_error(z3_enum_sort(ctx, "Bad", c("a", "")), "distinct")
  # Since Z3 4.12.0 an enumeration cannot reuse a declared name.
  if (z3_version_at_least("4.12.0")) expect_error(z3_enum_sort(ctx, "Dir", c("up", "down")))

  L <- z3_list_sort(ctx, "Path", Dir)
  expect_named(L, c("sort", "nil", "is_nil", "cons", "is_cons", "head", "tail"))
  l <- L$cons(Dir$north, L$cons(Dir$south, L$nil))
  expect_true(z3_identical(z3_simplify(L$head(L$tail(l))), Dir$south))
  expect_true(z3_value(z3_simplify(L$is_nil(L$tail(L$tail(l))))))
  expect_true(z3_identical(z3_datatype_of(L$sort)$tail, L$tail))
  IL <- z3_list_sort(ctx, "IL", I)
  expect_identical(z3_value(z3_simplify(IL$head(IL$cons(4, IL$nil)))), 4)
  expect_error(z3_list_sort(ctx, "Bad", "Int"), "z3_sort")
})

test_that("a single datatype reads its declarations back from Z3", {
  ctx <- z3_context()
  Nat <- z3_datatype(ctx, "Nat", zero = list(), succ = list(pred = "Nat"))
  expect_named(Nat, c("sort", "zero", "is_zero", "succ", "is_succ", "pred"))
  again <- z3_datatype_of(Nat$sort)
  expect_true(z3_identical(Nat$succ, again$succ))
  expect_true(z3_identical(Nat$is_zero, again$is_zero))
  expect_true(z3_identical(Nat$pred, again$pred))
  one <- Nat$succ(Nat$zero)
  expect_true(z3_identical(z3_simplify(Nat$pred(Nat$succ(one))), one))
  n <- z3_const(ctx, "n", Nat$sort)
  expect_identical(check_status(ctx, n == Nat$succ(n)), "unsat")
  expect_error(z3_datatype(ctx, "", a = list()), "empty")
})

test_that("tuple sorts and their readers", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  B <- z3_bool_sort(ctx)
  # One constructor named like the datatype: a Z3 tuple sort
  Pt <- z3_datatype(ctx, "Pt", Pt = list(x = I, flag = B))
  expect_named(Pt, c("sort", "Pt", "is_Pt", "x", "flag"))
  p <- Pt$Pt(3, TRUE)
  expect_identical(z3_value(z3_simplify(Pt$x(p))), 3)
  expect_true(z3_value(z3_simplify(Pt$is_Pt(p))))
  tf <- z3_tuple_fields(Pt)
  expect_named(tf, c("constructor", "fields"))
  expect_named(tf$fields, c("x", "flag"))
  expect_true(z3_identical(tf$constructor, Pt$Pt))
  expect_true(z3_identical(tf$fields$flag, Pt$flag))
  expect_false(z3_value(z3_simplify(tf$fields$flag(tf$constructor(1, FALSE)))))
  # z3_tuple_sort() keeps its mk_<name> constructor and is a tuple for Z3
  P <- z3_tuple_sort(ctx, "Pair", first = I, second = B)
  expect_true(z3_identical(z3_tuple_fields(P$sort)$constructor, P$mk_Pair))
  expect_named(z3_tuple_fields(P)$fields, c("first", "second"))
  Tree <- z3_datatype(ctx, "Tree", leaf = list(), node = list(l = "Tree", r = "Tree"))
  expect_error(z3_tuple_fields(Tree), "not a tuple sort")
  expect_error(z3_tuple_fields(I), "not a tuple sort")
})

test_that("patterns print in Z3's syntax", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", I, I)
  g <- z3_function(ctx, "g", I, I)
  x <- z3_int(ctx, "x")
  p <- z3_pattern(f(x), g(x))
  expect_s3_class(p, "z3_pattern")
  expect_length(p, 2)
  expect_match(format(p), "(f x)", fixed = TRUE)
  expect_match(format(p), "(g x)", fixed = TRUE)
  expect_output(print(p), "<z3_pattern>")
  expect_error(z3_pattern(), "one or more")
  expect_error(z3_pattern(1), "one or more")
})

test_that("quantifiers over constants accept every combination of options", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", I, I)
  x <- z3_int(ctx, "x")
  v0 <- z3_bound_var(ctx, 0, I)
  plain <- z3_quantifier_info(z3_exists(x, f(x) == 7))
  expect_identical(plain$type, "exists")
  expect_identical(plain$names, "x")
  expect_length(plain$patterns, 0)
  expect_identical(z3_quantifier_info(z3_forall(x, f(x) > 0, weight = 4))$weight, 4L)
  pat <- z3_quantifier_info(z3_forall(x, f(x) > 0, patterns = z3_pattern(f(x))))
  expect_length(pat$patterns, 1)
  expect_true(z3_identical(pat$patterns[[1]][[1]], f(v0)))
  expect_length(z3_quantifier_info(z3_forall(x, f(x) > 0, patterns = list(f(x))))$patterns, 1)
  expect_identical(check_status(ctx, z3_forall(x, f(x) > x, patterns = z3_pattern(f(x))), f(2) < 1), "unsat")
  named <- z3_quantifier_info(z3_forall(x, f(x) > 0, qid = "pos"))
  if (z3_version_at_least("4.12.3")) expect_identical(named$id, "pos")
  expect_error(z3_forall(x, f(x) > 0, patterns = z3_pattern(f(x)), no_patterns = list(f(x))), "not both")
  expect_error(z3_forall(x, f(x) > 0, patterns = list(list())), "at least one term")
})

test_that("de Bruijn quantifiers and lambdas", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  B <- z3_bool_sort(ctx)
  v0 <- z3_bound_var(ctx, 0, I)
  v1 <- z3_bound_var(ctx, 1, I)
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  # Index 0 is the last binder, so this is forall x y. x < y
  q <- z3_quantifier_db(list(I, I), c("x", "y"), v1 < v0)
  ref <- z3_forall(list(x, y), x < y)
  info <- z3_quantifier_info(q)
  expect_identical(info$type, "forall")
  expect_identical(info$names, c("x", "y"))
  expect_true(z3_identical(info$body, z3_quantifier_info(ref)$body))
  expect_identical(check_status(ctx, q), "unsat")
  expect_identical(check_status(ctx, !z3_quantifier_db(I, "x", v0 + 0 == v0)), "unsat")
  e <- z3_quantifier_db(I, "x", v0 > 5, type = "exists")
  expect_identical(z3_quantifier_info(e)$type, "exists")
  expect_identical(check_status(ctx, e), "sat")

  sq <- z3_quantifier_db(I, "i", v0 * v0, type = "lambda")
  expect_identical(z3_quantifier_info(sq)$type, "lambda")
  expect_identical(z3_sort_kind(sq), "array")
  expect_identical(z3_value(z3_simplify(z3_select(sq, 7))), 49)

  # Nested binders: forall x. exists y. y > x
  inner <- z3_quantifier_db(I, "y", v0 > v1, type = "exists")
  outer <- z3_quantifier_db(I, "x", inner)
  expect_true(z3_is_quantifier(z3_quantifier_info(outer)$body))
  expect_error(z3_quantifier_db(B, "x", inner), "has sort")

  f <- z3_function(ctx, "f", I, I)
  pq <- z3_quantifier_db(I, "x", f(v0) > 0, patterns = z3_pattern(f(v0)))
  expect_length(z3_quantifier_info(pq)$patterns, 1)
  expect_identical(check_status(ctx, pq, f(2) < 0), "unsat")
  expect_identical(z3_quantifier_info(z3_quantifier_db(I, "x", f(v0) > 0, weight = 5))$weight, 5L)
  nq <- z3_quantifier_info(z3_quantifier_db(I, "x", f(v0) > 0, qid = "fpos", no_patterns = list(f(v0))))
  expect_length(nq$no_patterns, 1)
  if (z3_version_at_least("4.12.3")) expect_identical(nq$id, "fpos")

  # Variables in patterns and no-patterns must match their binders too, also
  # in the annotations of a nested quantifier.
  tt <- z3_bool_val(ctx, TRUE)
  expect_error(z3_quantifier_db(B, "b", tt, patterns = z3_pattern(f(v0))),
               "has sort Int but its binder 'b' has sort Bool")
  expect_error(z3_quantifier_db(B, "b", tt, no_patterns = list(f(v0))),
               "has sort Int but its binder 'b' has sort Bool")
  nested <- z3_quantifier_db(I, "y", v0 > 0, no_patterns = list(f(v1)))
  expect_error(z3_quantifier_db(B, "b", nested), "has sort Int but its binder 'b' has sort Bool")
  expect_true(z3_is_well_sorted(z3_quantifier_db(I, "x", nested)))

  expect_error(z3_quantifier_db(list(I, I), "x", v0 > 0), "same length")
  expect_error(z3_quantifier_db(I, "x", v0 + 1), "Boolean")
  expect_error(z3_quantifier_db(B, "p", v0 > 0), "has sort")
  expect_error(z3_quantifier_db(list(), character(), v0 > 0), "at least one")
  expect_error(z3_quantifier_db(I, 1, v0 > 0), "character")
  expect_error(z3_quantifier_db(I, NA_character_, v0 > 0), "missing")
  expect_error(z3_quantifier_db(I, "i", v0, type = "lambda", weight = 1), "lambda takes no")
  expect_error(z3_quantifier_db(I, "x", v0 > 0, type = "some"), "should be one of")
})
