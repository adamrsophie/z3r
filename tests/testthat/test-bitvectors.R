test_that("bit-vector arithmetic wraps around", {
  ctx <- z3_context()
  bv <- function(v, w = 8) z3_bv_val(ctx, v, w)
  val <- function(e, ...) z3_value(z3_simplify(e), ...)
  expect_identical(val(bv(255) + 1), 0)
  expect_identical(val(bv(0) - 1), 255)
  expect_identical(val(bv(16) * 16), 0)
  expect_identical(val(-bv(1)), 255)
  expect_identical(val(bv(200), signed = TRUE), -56)
  expect_identical(val(bv(-1)), 255)
  expect_identical(val(bv(-128)), 128)
  expect_error(bv(256), "does not fit")
  expect_error(bv(-129), "does not fit")
  expect_error(bv(1.5), "whole numbers|not a whole")
  expect_identical(val(z3_bv_val(ctx, "18446744073709551615", 64) + 1), 0)
})

test_that("signed and unsigned operations differ where they should", {
  ctx <- z3_context()
  bv <- function(v) z3_bv_val(ctx, v, 8)
  val <- function(e) z3_value(z3_simplify(e))
  expect_true(val(z3_bvugt(bv(200), bv(100))))
  expect_true(val(z3_bvslt(bv(200), bv(100))))
  expect_true(val(z3_bvule(bv(5), bv(5))))
  expect_false(val(z3_bvsge(bv(255), bv(0))))
  expect_identical(val(z3_bvudiv(bv(200), bv(3))), 66)
  expect_identical(z3_value(z3_simplify(z3_bvsdiv(bv(-7), bv(2))), signed = TRUE), -3)
  expect_identical(z3_value(z3_simplify(z3_bvsrem(bv(-7), bv(2))), signed = TRUE), -1)
  expect_identical(z3_value(z3_simplify(z3_bvsmod(bv(-7), bv(2))), signed = TRUE), 1)
  expect_identical(val(z3_bvurem(bv(7), bv(0))), 7)
  expect_identical(val(z3_bvudiv(bv(7), bv(0))), 255)
})

test_that("bitwise operations and shifts", {
  ctx <- z3_context()
  bv <- function(v) z3_bv_val(ctx, v, 8)
  val <- function(e) z3_value(z3_simplify(e))
  expect_identical(val(bv(0xF0) & bv(0x3C)), as.numeric(bitwAnd(0xF0, 0x3C)))
  expect_identical(val(bv(0xF0) | bv(0x0F)), 255)
  expect_identical(val(!bv(0x0F)), 0xF0)
  expect_identical(val(z3_bvxor(bv(0xFF), bv(0x0F))), 0xF0)
  expect_identical(val(z3_bvshl(bv(1), bv(7))), 128)
  expect_identical(val(z3_bvlshr(bv(0x80), bv(7))), 1)
  expect_identical(val(z3_bvashr(bv(0x80), bv(7))), 255)
  expect_identical(val(z3_rotate_left(bv(0x81), 1)), 3)
  expect_identical(val(z3_rotate_right(bv(0x81), 1)), 0xC0)
})

test_that("width changes", {
  ctx <- z3_context()
  x <- z3_bv_val(ctx, 0xAB, 8)
  val <- function(e) z3_value(z3_simplify(e))
  expect_identical(val(z3_extract(x, 7, 4)), 10)
  expect_identical(z3_bv_width(z3_extract(x, 7, 4)), 4L)
  expect_identical(val(z3_concat(z3_bv_val(ctx, 1, 4), z3_bv_val(ctx, 2, 4))), 18)
  expect_identical(val(z3_zero_ext(x, 8)), 0xAB)
  expect_identical(val(z3_sign_ext(x, 8)), 0xFFAB)
  expect_identical(val(z3_repeat(z3_bv_val(ctx, 1, 2), 3)), 21)
  expect_error(z3_extract(x, 8, 0), "width")
  expect_error(z3_extract(x, 2, 3), "high >= low")
  expect_error(x + z3_bv_val(ctx, 1, 16), "equal width")
})

test_that("conversions between bit-vectors and integers", {
  ctx <- z3_context()
  x <- z3_bv_val(ctx, 250, 8)
  expect_identical(z3_value(z3_simplify(z3_bv2int(x))), 250)
  expect_identical(z3_value(z3_simplify(z3_bv2int(x, signed = TRUE))), -6)
  expect_identical(z3_value(z3_simplify(z3_int2bv(z3_int_val(ctx, 300), 8))), 44)
  expect_identical(z3_value(z3_simplify(z3_int2bv(z3_int_val(ctx, -1), 8))), 255)
})

test_that("solving with bit-vectors and overflow predicates", {
  ctx <- z3_context()
  x <- z3_bv(ctx, "x", 8)
  y <- z3_bv(ctx, "y", 8)
  # x + y overflows unsigned but the sum is small
  s <- z3_solver(ctx)
  z3_add(s, !z3_bvadd_no_overflow(x, y, signed = FALSE), z3_bvult(x + y, 10), x == 250)
  expect_identical(z3_check(s), "sat")
  m <- z3_model(s)
  yv <- z3_value(z3_eval(m, y))
  expect_true(yv >= 6 && yv <= 15)
  expect_true((250 + yv) %% 256 < 10)
  # Classic: x & (x - 1) == 0 characterizes powers of two (and zero)
  s2 <- z3_solver(ctx)
  z3_add(s2, (x & (x - 1)) == 0, x != 0, z3_bvugt(x, 64))
  expect_identical(z3_check(s2), "sat")
  expect_identical(z3_value(z3_eval(z3_model(s2), x)), 128)
})
