test_that("multi-index arrays", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  B <- z3_bool_sort(ctx)
  A2 <- z3_array(ctx, "A2", list(I, I), B)
  expect_identical(check_status(ctx, z3_select(z3_store(A2, list(1, 2), TRUE), 1, 2) == FALSE), "unsat")
  expect_identical(check_status(ctx, z3_select(z3_store(A2, list(1, 2), TRUE), 2, 1) == FALSE), "sat")
  expect_error(z3_select(A2, 1), "2 index")
  expect_length(z3_array_sort_info(A2)$domain, 2L)
})

test_that("map, default, extensionality, as-array and lambdas", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  a <- z3_array(ctx, "a", I, I)
  b <- z3_array(ctx, "b", I, I)
  x <- z3_int(ctx, "x")
  plus <- z3_function(ctx, "plus", list(I, I), I)
  m <- z3_array_map(plus, a, b)
  expect_identical(z3_sort_kind(m), "array")
  expect_identical(check_status(ctx, a != b, z3_select(a, z3_array_ext(a, b)) == z3_select(b, z3_array_ext(a, b))), "unsat")
  expect_identical(check_status(ctx, z3_array_default(z3_const_array(I, 4)) != 4), "unsat")
  sq <- z3_lambda(x, x * x)
  expect_identical(z3_value(z3_simplify(z3_select(sq, 7))), 49)
  f <- z3_function(ctx, "f", I, I)
  expect_identical(check_status(ctx, z3_select(z3_as_array(f), 3) != f(3)), "unsat")
  expect_error(z3_lambda(x + 1, x), "constants")
})

test_that("set operations", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  S <- z3_set_sort(I)
  st <- z3_const(ctx, "st", S)
  e <- z3_empty_set(I)
  one_two <- z3_set_add(z3_set_add(e, 1), 2)
  expect_identical(check_status(ctx, z3_set_member(3, st), z3_set_subset(st, z3_set_add(e, 4))), "unsat")
  expect_true(z3_value(z3_simplify(z3_set_member(2, z3_set_union(z3_set_add(e, 1), z3_set_add(e, 2))))))
  expect_false(z3_value(z3_simplify(z3_set_member(1, z3_set_intersect(z3_set_add(e, 1), z3_set_add(e, 2))))))
  expect_false(z3_value(z3_simplify(z3_set_member(2, z3_set_del(one_two, 2)))))
  expect_true(z3_value(z3_simplify(z3_set_member(5, z3_set_complement(e)))))
  expect_true(z3_value(z3_simplify(z3_set_member(9, z3_full_set(I)))))
  expect_identical(check_status(ctx, z3_set_member(1, z3_set_difference(one_two, z3_set_add(e, 1)))), "unsat")
  expect_error(z3_set_union(z3_int(ctx, "x")), "sets")
})
