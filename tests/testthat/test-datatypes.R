test_that("recursive datatypes: constructors, recognizers, accessors", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  Tree <- z3_datatype(ctx, "Tree", leaf = list(), node = list(left = "Tree", value = I, right = "Tree"))
  expect_s3_class(Tree, "z3_datatype")
  expect_identical(z3_sort_kind(Tree$sort), "datatype")
  t <- z3_const(ctx, "t", Tree$sort)
  s <- z3_solver(ctx)
  z3_add(s, Tree$is_node(t), Tree$value(t) == 7, Tree$is_node(Tree$left(t)))
  expect_identical(z3_check(s), "sat")
  m <- z3_model(s)
  expect_true(z3_value(z3_eval(m, Tree$is_node(Tree$left(t)))))
  expect_identical(z3_value(z3_eval(m, Tree$value(t))), 7)
  # Constructors are injective and distinct
  expect_identical(check_status(ctx, Tree$leaf == Tree$node(Tree$leaf, 1, Tree$leaf)), "unsat")
  expect_identical(check_status(ctx, Tree$node(Tree$leaf, 1, Tree$leaf) == Tree$node(Tree$leaf, 2, Tree$leaf)), "unsat")
  # No infinite trees
  expect_identical(check_status(ctx, t == Tree$node(t, 1, Tree$leaf)), "unsat")
  expect_output(print(Tree), "node\\(left: Tree, value: Int, right: Tree\\)")
  skip_if_not(z3_version_at_least("4.15.0"))
  expect_true(z3_is_recursive_datatype(Tree))
})

test_that("enumerations, tuples and lists", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  Color <- z3_enum_sort(ctx, "Color", c("red", "green", "blue"))
  cs <- lapply(1:4, function(i) z3_const(ctx, paste0("k", i), Color$sort))
  expect_identical(check_status(ctx, z3_distinct(cs)), "unsat")
  c1 <- z3_const(ctx, "c1", Color$sort)
  s <- z3_solver(ctx)
  z3_add(s, c1 != Color$red, c1 != Color$green)
  z3_check(s)
  expect_true(z3_identical(z3_eval(z3_model(s), c1), Color$blue))
  expect_error(z3_enum_sort(ctx, "Bad", c("a", "a")), "distinct")
  P <- z3_tuple_sort(ctx, "Pair", first = I, second = z3_bool_sort(ctx))
  p <- P$mk_Pair(3, TRUE)
  expect_identical(z3_value(z3_simplify(P$first(p))), 3)
  expect_false(z3_value(z3_simplify(P$second(z3_update_field(p, P$second, FALSE)))))
  L <- z3_list_sort(ctx, "IntList", I)
  l <- L$cons(1, L$cons(2, L$nil))
  expect_identical(z3_value(z3_simplify(L$head(L$tail(l)))), 2)
  expect_true(z3_value(z3_simplify(L$is_nil(L$tail(L$tail(l))))))
  expect_identical(format(z3_datatype_of(Color$sort)$blue), "blue")
})

test_that("mutually recursive datatypes and errors", {
  ctx <- z3_context()
  dts <- z3_datatypes(ctx, list(
    TreeM = list(empty = list(), branch = list(kids = "Forest")),
    Forest = list(nilf = list(), consf = list(car = "TreeM", cdr = "Forest"))
  ))
  expect_named(dts, c("TreeM", "Forest"))
  f <- z3_const(ctx, "f", dts$Forest$sort)
  expect_identical(check_status(ctx, dts$Forest$is_consf(f), dts$TreeM$is_branch(dts$Forest$car(f))), "sat")
  expect_error(z3_datatype(ctx, "Bad", a = list(x = "Nope")), "unknown datatype")
  expect_error(z3_datatype(ctx, "Bad", list()), "named")
  expect_error(z3_datatype(ctx, "Bad", a = list(1)), "must be named")
  expect_error(z3_datatypes(ctx, list(list())), "distinct names")
})

test_that("polymorphic datatypes", {
  skip_if_not(z3_version_at_least("4.15.4"))
  ctx <- z3_context()
  A <- z3_type_variable(ctx, "A")
  Box <- z3_datatype(ctx, "Box", box = list(content = A), parameters = list(A))
  BI <- z3_datatype_instance(ctx, "Box", z3_int_sort(ctx))
  b <- z3_const(ctx, "b", BI$sort)
  s <- z3_solver(ctx)
  z3_add(s, BI$content(b) == 5)
  expect_identical(z3_check(s), "sat")
  expect_identical(format(z3_eval(z3_model(s), b)), "(box 5)")
})

test_that("member names that collide are refused", {
  ctx <- z3_context()
  expect_error(z3_datatype(ctx, "D1", sort = list()), "reserved")
  I <- z3_int_sort(ctx)
  expect_error(z3_datatype(ctx, "D2", a = list(x = I), b = list(x = I)), "used twice")
  expect_error(z3_datatype(ctx, "D3", p = list(is_q = I), q = list()), "used twice")
  expect_error(z3_datatypes(ctx, list(T1 = list(a = list(x = I), b = list(x = I)))),
               "used twice in datatype T1")
  expect_error(z3_enum_sort(ctx, "E1", c("a", "is_a")), "used twice in datatype E1")
  expect_error(z3_enum_sort(ctx, "E2", c("sort", "b")), "reserved")
})

test_that("an enumeration declared again says why Z3 refuses it", {
  skip_if_not(z3_version_at_least("4.12.0"))
  ctx <- z3_context()
  Color <- z3_enum_sort(ctx, "Color", c("red", "green"))
  expect_error(z3_enum_sort(ctx, "Color", c("red", "green")), "already declared in this context")
  expect_identical(check_status(ctx, z3_const(ctx, "c1", Color$sort) != Color$red), "sat")
})

test_that("a refused datatype leaves its name free for a corrected one", {
  # The names are checked before Z3 declares the sort.
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  expect_error(z3_enum_sort(ctx, "E", c("a", "is_a")), "used twice")
  E <- z3_enum_sort(ctx, "E", c("a", "b"))
  expect_identical(attr(E, "constructors"), c("a", "b"))
  expect_error(z3_datatype(ctx, "D", p = list(is_q = I), q = list()), "used twice")
  D <- z3_datatype(ctx, "D", p = list(v = I), q = list())
  expect_identical(attr(D, "constructors"), c("p", "q"))
  expect_error(z3_datatype(ctx, "P", P = list(x = I, x = I)), "used twice")
  P <- z3_datatype(ctx, "P", P = list(x = I, y = I))
  expect_identical(format(P$sort), "P")
})
