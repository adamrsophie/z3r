test_that("regular expressions", {
  ctx <- z3_context()
  s <- z3_string(ctx, "s")
  digits <- z3_re_plus(z3_re_range("0", "9", ctx))
  v <- solve_values(ctx, z3_in_re(s, z3_re_concat(z3_string_val(ctx, "id-"), digits)), z3_length(s) == 6,
                    vars = list(s = s))$s
  expect_match(v, "^id-[0-9]{3}$")
  # digits+ is contained in digits*; Z3 5.4.1 proves it, Z3 4.16 answers
  # "unknown". Either way the answer must never be "sat".
  sv <- z3_solver(ctx, timeout = 10000)
  z3_add(sv, z3_in_re(s, digits), !z3_in_re(s, z3_re_star(z3_re_range("0", "9", ctx))))
  expect_false(z3_check(sv) == "sat")
  expect_identical(solve_values(ctx, z3_in_re(s, z3_re_loop(z3_re_range("a", "a", ctx), 3, 3)), vars = list(s))[[1]], "aaa")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_intersect(digits, z3_re_star(z3_re_range("a", "z", ctx))))), "unsat")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_complement(z3_re_full(z3_re_sort(z3_string_sort(ctx)))))), "unsat")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_empty(z3_re_sort(z3_string_sort(ctx))))), "unsat")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_allchar(z3_re_sort(z3_string_sort(ctx)))), z3_length(s) == 1), "sat")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_option(z3_re(z3_string_val(ctx, "ab")))), z3_length(s) == 1), "unsat")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_union(z3_re(z3_string_val(ctx, "a")), "b")), s == "b"), "sat")
  expect_error(z3_re_range("a", "z"), "needs ctx")
  expect_error(z3_re("abc"), "Z3 expression")
  expect_identical(solve_values(ctx, z3_in_re(s, z3_re_power(z3_re_range("x", "x", ctx), 4)), vars = list(s))[[1]], "xxxx")
  expect_identical(check_status(ctx, z3_in_re(s, z3_re_diff(digits, z3_re_star(z3_re_range("0", "9", ctx))))), "unsat")
})

test_that("general sequences", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  q <- z3_const(ctx, "q", z3_seq_sort(I))
  unit <- function(v) z3_seq_unit(z3_int_val(ctx, v))
  s <- z3_solver(ctx)
  z3_add(s, z3_length(q) == 3, z3_seq_nth(q, 0) == 7, z3_contains(q, z3_concat(unit(1), unit(2))))
  expect_identical(z3_check(s), "sat")
  expect_identical(format(z3_eval(z3_model(s), q)), "(seq.++ (seq.unit 7) (seq.unit 1) (seq.unit 2))")
  expect_true(z3_sort_basis(z3_seq_sort(I)) == I)
  expect_identical(z3_value(z3_simplify(z3_length(z3_seq_empty(z3_seq_sort(I))))), 0)
  expect_identical(z3_value(z3_simplify(z3_last_indexof(z3_string_val(ctx, "abcabc"), "bc"))), 4)
  expect_error(z3_concat(unit(1), z3_string_val(ctx, "a")), "sequences of one sort")
  expect_error(z3_seq_nth(z3_int(ctx, "x"), 0), "sequence")
})

test_that("characters and code points", {
  ctx <- z3_context()
  expect_identical(z3_sort_kind(z3_char_sort(ctx)), "char")
  expect_identical(z3_value(z3_simplify(z3_str_at(z3_string_val(ctx, "hello"), 1))), "e")
  expect_identical(z3_value(z3_simplify(z3_ubv_to_str(z3_bv_val(ctx, 200, 8)))), "200")
  expect_identical(z3_value(z3_simplify(z3_sbv_to_str(z3_bv_val(ctx, 200, 8)))), "-56")
  skip_if_not(z3_version_at_least("4.8.15"))
  a <- z3_char_val(ctx, 65)
  expect_identical(z3_value(z3_simplify(z3_char_to_int(a))), 65)
  expect_identical(z3_value(z3_simplify(z3_str_to_code(z3_string_val(ctx, "A")))), 65)
  expect_identical(z3_value(z3_simplify(z3_str_from_code(z3_int_val(ctx, 955)))), "\u03bb")
  expect_true(z3_value(z3_simplify(z3_char_le(a, z3_char_val(ctx, 66)))))
  expect_false(z3_value(z3_simplify(z3_char_is_digit(a))))
  expect_identical(check_status(ctx, z3_bv2int(z3_char_to_bv(a)) != 65), "unsat")
  expect_error(z3_char_val(ctx, -1), "code")
})

test_that("newer sequence operations", {
  ctx <- z3_context()
  skip_if_not(z3_version_at_least("4.13.2"))
  x <- z3_int(ctx, "x")
  unit <- function(v) z3_seq_unit(z3_int_val(ctx, v))
  sq <- z3_lambda(x, x * x)
  expect_identical(format(z3_simplify(z3_seq_map(sq, z3_concat(unit(2), unit(3))))),
                   "(seq.++ (seq.unit 4) (seq.unit 9))")
  acc <- z3_int(ctx, "acc")
  el <- z3_int(ctx, "el")
  r <- z3_int(ctx, "r")
  v <- solve_values(ctx, r == z3_seq_foldl(z3_lambda(list(acc, el), acc + el), 0, z3_concat(unit(5), unit(6))),
                    vars = list(r = r))
  expect_identical(v$r, 11)
  skip_if_not(z3_version_at_least("4.15.5"))
  expect_identical(z3_value(z3_simplify(z3_replace_all(z3_string_val(ctx, "a-b-c"), "-", "+"))), "a+b+c")
  s <- z3_string(ctx, "s")
  digits <- z3_re_plus(z3_re_range("0", "9", ctx))
  r <- z3_replace_re_all(z3_string_val(ctx, "a1b22c"), digits, "#")
  expect_identical(z3_sort_kind(r), "string")
  # Z3's string solver is incomplete for regular-expression replacement.
  expect_true(check_status(ctx, r != "a#b#c") %in% c("unsat", "unknown"))
  skip_if_not(z3_version_at_least("5.3.0"))
  expect_identical(solve_values(ctx, s == z3_seq_power(z3_string_val(ctx, "ab"), 3), vars = list(s))[[1]], "ababab")
})

test_that("string literals stay within Z3's characters", {
  ctx <- z3_context()
  expect_error(z3_string_val(ctx, "\U000E0001"), "beyond U\\+2FFFF")
  expect_identical(z3_value(z3_string_val(ctx, "\U0002FFFF")), "\U0002FFFF")
})
