test_that("AST maps store and replace values by term structure", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  m <- z3_ast_map(ctx)
  expect_s3_class(m, "z3_ast_map")
  expect_identical(length(m), 0L)
  expect_invisible(z3_ast_map_insert(m, x + 1, y))
  z3_ast_map_insert(m, x, z3_int_val(ctx, 3))
  expect_identical(length(m), 2L)
  expect_true(z3_ast_map_contains(m, x + 1))
  expect_false(z3_ast_map_contains(m, y))
  expect_false(z3_ast_map_contains(m, 1 + x))
  expect_true(z3_identical(z3_ast_map_get(m, x + 1), y))
  expect_null(z3_ast_map_get(m, y))
  z3_ast_map_insert(m, x, z3_int_val(ctx, 4))
  expect_identical(length(m), 2L)
  expect_identical(z3_value(z3_ast_map_get(m, x)), 4)
})

test_that("AST map keys and values line up", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  m <- z3_ast_map(ctx)
  z3_ast_map_insert(m, x, y + 1)
  z3_ast_map_insert(m, y, x * 2)
  keys <- z3_ast_map_keys(m)
  vals <- z3_ast_map_values(m)
  expect_length(keys, 2L)
  expect_length(vals, 2L)
  expect_setequal(vapply(keys, format, ""), c("x", "y"))
  for (i in seq_along(keys)) {
    expect_true(z3_identical(z3_ast_map_get(m, keys[[i]]), vals[[i]]))
  }
})

test_that("AST maps erase, reset and print", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  m <- z3_ast_map(ctx)
  z3_ast_map_insert(m, x, y)
  z3_ast_map_insert(m, y, x)
  expect_match(format(m), "ast-map", fixed = TRUE)
  expect_identical(as.character(m), format(m))
  expect_output(print(m), "z3_ast_map")
  expect_invisible(z3_ast_map_erase(m, x))
  expect_false(z3_ast_map_contains(m, x))
  expect_identical(length(m), 1L)
  expect_no_error(z3_ast_map_erase(m, x))
  expect_identical(length(m), 1L)
  expect_invisible(z3_ast_map_reset(m))
  expect_identical(length(m), 0L)
  expect_identical(z3_ast_map_keys(m), list())
  expect_identical(z3_ast_map_values(m), list())
})

test_that("AST maps accept only expressions of their context", {
  a <- z3_context()
  b <- z3_context()
  x <- z3_int(a, "x")
  m <- z3_ast_map(a)
  expect_error(z3_ast_map_insert(m, z3_int(b, "x"), x), "different contexts")
  expect_error(z3_ast_map_insert(m, x, z3_int(b, "y")), "different contexts")
  expect_error(z3_ast_map_contains(m, z3_int(b, "x")), "different contexts")
  expect_error(z3_ast_map_get(m, z3_int(b, "x")), "different contexts")
  expect_error(z3_ast_map_insert(m, x, 1), "must be a Z3 expression")
  expect_error(z3_ast_map_insert(m, 1, x), "must be a Z3 expression")
  expect_error(z3_ast_map_insert(z3_solver(a), x, x), "z3_ast_map")
  expect_error(length(structure(1, class = "z3_ast_map")), "z3_ast_map")
})

test_that("lists of terms translate in one step", {
  a <- z3_context()
  b <- z3_context()
  x <- z3_int(a, "x")
  y <- z3_int(a, "y")
  out <- z3_translate(list(p = x + 1, q = y), b)
  expect_named(out, c("p", "q"))
  expect_true(all(vapply(out, z3_same_context, TRUE, b)))
  expect_identical(format(out$p), "(+ x 1)")
  expect_identical(z3_translate(list(), b), list())
  same <- list(x, y)
  expect_identical(z3_translate(same, a), same)
  expect_error(z3_translate(list(x, z3_int(b, "z")), b), "different contexts")
  expect_error(z3_translate(list(x, 1), b), "Z3 expressions")
})

