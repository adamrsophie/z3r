test_that("z3_linear builds dense and sparse systems exactly", {
  ctx <- z3_context()
  x <- z3_ints(ctx, c("a", "b", "c"))
  A <- rbind(r1 = c(1, 2, 0), r2 = c(0, 1, -1))
  cons <- z3_linear(A, x, "<=", c(10, 0))
  expect_named(cons, c("r1", "r2"))
  s <- z3_solver(ctx)
  z3_add(s, cons[[1]] != (x$a + 2 * x$b <= 10))
  expect_identical(z3_check(s), "unsat")
  s <- z3_solver(ctx)
  z3_add(s, z3_linear(A, x, ">=", c(4, 1)), z3_linear(diag(3), x, ">=", 0))
  expect_identical(z3_check(s), "sat")
  y <- z3_reals(ctx, c("p", "q"))
  e <- z3_linear(list(row = c(1, 1), col = 1:2, value = c("1/3", "2/3")), y, "==", "1")
  s <- z3_solver(ctx)
  z3_add(s, e, y$p == y$q, y$p != 1)
  expect_identical(z3_check(s), "unsat")
  # Empty rows, op per row, mixed Int and Real.
  mix <- list(x$a, y$p)
  r <- z3_linear(rbind(c(0, 0), c(1, 1)), mix, c("==", "<"), list(0, "1/2"))
  expect_length(r, 2L)
  expect_identical(z3_sort_kind(r[[2]]), "bool")
  expect_error(z3_linear(A, x[1:2], "<=", 1), "3 columns")
  expect_error(z3_linear(A, x, "<=", c(1, 2, 3)), "length 1")
  expect_error(z3_linear(A, x, "=<", 1), "op must be one of")
  expect_error(z3_linear(rbind(c(NA, 1, 1)), x, "<=", 1), "missing")
  old <- options(z3r.doubles = "error")
  on.exit(options(old))
  expect_error(z3_linear(rbind(c(0.1, 0, 0)), x, "<=", 1), "z3r.doubles")
})

test_that("z3_all_models streams assignments to on_model", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x >= 0, x < 5)
  seen <- c()
  r <- z3_all_models(s, x, on_model = function(v) { seen <<- c(seen, v$x); length(seen) < 3 })
  expect_identical(attr(r, "status"), "stopped")
  expect_identical(attr(r, "count"), 3L)
  expect_length(seen, 3L)
  expect_identical(z3_num_scopes(s), 0L)
  r2 <- z3_all_models(s, x, on_model = function(v) NULL)
  expect_identical(attr(r2, "status"), "unsat")
  expect_identical(attr(r2, "count"), 5L)
  expect_error(z3_all_models(s, x, on_model = function(v) stop("cb")), "cb")
  expect_identical(z3_num_scopes(s), 0L)
})

test_that("symcompR conversion translates shared subterms once", {
  skip_if_not_installed("symcompR")
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  t <- x
  for (i in 1:30) t <- t + t  # a DAG of 31 nodes, a tree of 2^30
  st <- system.time(e <- z3_to_symbolic(t))
  expect_lt(st[["elapsed"]], 30)
  sx <- symcompR::Symbol("x", integer = TRUE)
  u <- sx
  for (i in 1:20) u <- symcompR::Max(u, u + 1)
  expect_s3_class(z3_from_symbolic(ctx, u), "z3_expr")
})
