test_that("implied equalities group provably equal terms", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  z <- z3_int(ctx, "z")
  w <- z3_int(ctx, "w")
  s <- z3_solver(ctx)
  z3_add(s, x == y + 1, y + 1 == z)
  res <- z3_implied_equalities(s, list(x, y, z, w))
  expect_identical(res$status, "sat")
  expect_identical(res$class[1], res$class[3])
  expect_false(res$class[1] == res$class[2])
  expect_false(res$class[1] == res$class[4])
})

test_that("applications can be rebuilt with new arguments", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  expect_identical(format(z3_update_args(x + 1, list(x * 2, 5))), "(+ (* x 2) 5)")
  expect_error(z3_update_args(x + 1, list(x)), "2 argument")
  expect_error(z3_update_args(x + 1, list(x, TRUE)), "wrong sort")
})

test_that("files, parser contexts and model converters", {
  ctx <- z3_context()
  f <- tempfile(fileext = ".smt2")
  on.exit(unlink(f))
  writeLines(c("(declare-const a Int)", "(assert (> a 4))", "(assert (< a 6))"), f)
  s <- z3_solver(ctx)
  z3_add_smtlib(s, file = f)
  expect_identical(z3_check(s), "sat")
  expect_identical(z3_value(z3_eval(z3_model(s), z3_int(ctx, "a"))), 5)
  expect_error(z3_add_smtlib(s), "exactly one")
  expect_error(z3_add_smtlib(s, file = tempfile()), "existing file")
  s2 <- z3_solver(ctx)
  expect_invisible(z3_import_model_converter(s, s2))
  # Fresh, never used solvers (Z3 crashes on these without z3r's guard)
  expect_invisible(z3_import_model_converter(z3_solver(ctx), z3_solver(ctx)))
  expect_type(z3_cube(z3_solver(ctx), list()), "list")
  skip_if_not(z3_version_at_least("4.9.0"))
  p <- z3_parser(ctx)
  g <- z3_function(ctx, "g", z3_int_sort(ctx), z3_int_sort(ctx))
  z3_parser_add(p, g)
  z3_parser_add(p, z3_uninterpreted_sort(ctx, "U"))
  a1 <- z3_parse(p, "(declare-const b Int) (assert (> (g b) 3))")
  a2 <- z3_parse(p, "(assert (< b 0)) (declare-const u U)")
  expect_length(a1, 1L)
  expect_length(a2, 1L)
  expect_true(z3_identical(z3_args(z3_args(a1[[1]])[[1]])[[1]], z3_int(ctx, "b")))
})

test_that("numeral forms and constructors", {
  ctx <- z3_context()
  expect_identical(z3_binary_string(z3_int_val(ctx, 10)), "1010")
  bv <- z3_bv_from_bits(ctx, c(TRUE, FALSE, TRUE, TRUE))
  expect_identical(z3_bv_width(bv), 4L)
  expect_identical(z3_value(bv), 13)
  expect_error(z3_bv_from_bits(ctx, c(TRUE, NA)), "NA")
  D <- z3_fp64_sort(ctx)
  one_five <- z3_fp_from_parts(D, FALSE, 0, 2^51)
  expect_identical(z3_value(one_five), 1.5)
  expect_identical(z3_value(z3_fp_from_parts(D, TRUE, 1, 0)), -2)
  r <- z3_algebraic_root(z3_real_val(ctx, 2), 2)
  b <- z3_algebraic_bounds(r, 5)
  expect_true(z3_value(b$lower) < sqrt(2) && sqrt(2) < z3_value(b$upper))
  expect_lt(z3_value(b$upper) - z3_value(b$lower), 1e-5)
})

test_that("identity of sorts and declarations; memory, log and parameters", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  expect_true(z3_identical(I, z3_sort(z3_int(ctx, "x"))))
  expect_false(z3_identical(I, z3_real_sort(ctx)))
  f <- z3_function(ctx, "f", I, I)
  expect_true(z3_identical(f, z3_decl(f(1))))
  expect_type(z3_ast_id(I), "double")
  expect_type(z3_ast_id(f), "double")
  expect_gt(z3_memory_usage(), 0)
  log <- tempfile()
  on.exit(unlink(log))
  z3_log_open(log)
  z3_log_append("z3r test")
  z3_log_close()
  expect_true(file.exists(log))
  expect_invisible(z3_update_param(ctx, "timeout", 1000))
  expect_error(z3_update_param(ctx, "nonsense", 1), "unknown context parameter")
  q <- z3_quantifier_info(z3_forall(z3_int(ctx, "x"), z3_int(ctx, "x") > 0, qid = "myq"))
  expect_true("no_patterns" %in% names(q))
  if (z3_version_at_least("4.12.3")) expect_identical(q$id, "myq")
})
