test_that("sat, unsat and unknown are distinct results", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  expect_identical(check_status(ctx, x > 0, x < 2), "sat")
  expect_identical(check_status(ctx, x > 0, x < 1), "unsat")
  s <- z3_solver(ctx, rlimit = 1)
  y <- z3_int(ctx, "y")
  z3_add(s, x * y == z3_int_val(ctx, "1000000016000000063"), x > 1, y > 1)
  expect_identical(z3_check(s), "unknown")
  expect_match(z3_reason_unknown(s), "resource limit")
  expect_error(z3_model(s), "last result was \"unknown\"")
  expect_error(z3_unsat_core(s), "last result was \"unknown\"")
})

test_that("solutions satisfy the constraints", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  v <- solve_values(ctx, x + y == 10, x > 2 * y, y > 0, vars = list(x = x, y = y))
  expect_identical(v$x + v$y, 10)
  expect_gt(v$x, 2 * v$y)
  expect_gt(v$y, 0)
  # Linear system with a unique solution
  v <- solve_values(ctx, 3 * x + 2 * y == 36, x - y == 2, vars = list(x = x, y = y))
  expect_identical(v, list(x = 8, y = 6))
})

test_that("nonlinear integer and real problems", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  v <- solve_values(ctx, x * x + y * y == 25, x > y, y > 0, vars = list(x = x, y = y))
  expect_identical(v, list(x = 4, y = 3))
  r <- z3_real(ctx, "r")
  s <- z3_solver(ctx)
  z3_add(s, r * r == 2, r > 0)
  expect_identical(z3_check(s), "sat")
  root <- z3_eval(z3_model(s), r)
  expect_equal(z3_value(root, exact = FALSE), sqrt(2))
  expect_error(z3_value(root), "algebraic")
  expect_match(z3_decimal(root, 10), "^1\\.4142135623")
})

test_that("Boolean satisfiability", {
  ctx <- z3_context()
  p <- z3_bools(ctx, c("a", "b", "c"))
  v <- solve_values(ctx, p$a | p$b, !p$a | p$c, !p$b | !p$c, p$a, vars = p)
  expect_true(v$a)
  expect_true(v$c)
  expect_false(v$b)
  # Pigeonhole: 3 pigeons, 2 holes
  h <- lapply(1:3, function(i) z3_bools(ctx, paste0("p", i, "h", 1:2)))
  cons <- c(lapply(h, z3_or),
            lapply(1:2, function(j) {
              z3_and(unlist(lapply(1:2, function(i) lapply((i + 1):3, function(k) {
                !(h[[i]][[j]] & h[[k]][[j]])
              })), recursive = FALSE))
            }))
  expect_identical(check_status(ctx, cons), "unsat")
})

test_that("validity is checked by refuting the negation", {
  ctx <- z3_context()
  p <- z3_bool(ctx, "p")
  q <- z3_bool(ctx, "q")
  # De Morgan holds
  expect_identical(check_status(ctx, !(z3_iff(!(p & q), !p | !q))), "unsat")
  # Modus ponens
  expect_identical(check_status(ctx, !z3_implies(p & z3_implies(p, q), q)), "unsat")
  # Affirming the consequent does not
  expect_identical(check_status(ctx, !z3_implies(q & z3_implies(p, q), p)), "sat")
})

test_that("z3_add validates all constraints before asserting", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  expect_error(z3_add(s, x > 0, x + 1), "constraint 2 is not Boolean")
  expect_length(z3_assertions(s), 0L)
  z3_add(s, list(x > 0, x < 5), x != 2)
  expect_length(z3_assertions(s), 3L)
  z3_add(s, TRUE)
  expect_length(z3_assertions(s), 4L)
  expect_error(z3_add(s, 1:2), "length 1")
})

test_that("assertions are not modified by solving", {
