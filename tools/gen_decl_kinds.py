"""Generate src/decl_kinds.h from the C API headers of every Z3 release.

Usage: python3 tools/gen_decl_kinds.py HEADERS > src/decl_kinds.h

HEADERS holds one directory per release, named by its version (4.8.13,
4.9.0, ...), each containing that release's z3_api.h. Every enumerator of
Z3_decl_kind from 4.8.13 on is listed, guarded by the releases that declare
it, so the switch compiles against each of them.
"""
import os
import re
import sys

MIN = (4, 8, 13)


def ops(path):
    text = open(path).read()
    body = re.search(r"typedef enum \{(.*?)\} Z3_decl_kind;", text, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    return set(re.findall(r"\b(Z3_OP_[A-Z0-9_]+)\b", body))


root = sys.argv[1]
versions = sorted(
    (tuple(int(x) for x in d.split(".")), d)
    for d in os.listdir(root)
    if re.fullmatch(r"\d+\.\d+\.\d+", d) and os.path.exists(os.path.join(root, d, "z3_api.h"))
)
versions = [(v, d) for v, d in versions if v >= MIN]
present = {v: ops(os.path.join(root, d, "z3_api.h")) for v, d in versions}
order = [v for v, _ in versions]


def at_least(v):
    return "Z3R_AT_LEAST(%d, %d, %d)" % v


def guard(name):
    have = [v for v in order if name in present[v]]
    first, last = have[0], have[-1]
    span = order[order.index(first):order.index(last) + 1]
    if have != span:
        sys.exit("%s is missing from some releases between %s and %s" % (name, first, last))
    conds = []
    if first > order[0]:
        conds.append(at_least(first))
    if last < order[-1]:
        conds.append("!" + at_least(order[order.index(last) + 1]))
    return " && ".join(conds)


names = sorted(set().union(*present.values()))
print("// Generated by tools/gen_decl_kinds.py from the headers of Z3 %s to %s;"
      % (".".join(map(str, order[0])), ".".join(map(str, order[-1]))))
print("// do not edit by hand. Names of Z3_decl_kind values, each guarded by the")
print("// releases that declare it.")
print("#ifndef Z3R_DECL_KINDS_H")
print("#define Z3R_DECL_KINDS_H")
print("inline const char* decl_kind_name(Z3_decl_kind k) {")
print("  switch (k) {")
for name in names:
    g = guard(name)
    if g:
        print("#if " + g)
    print('    case %s: return "%s";' % (name, name[6:].lower()))
    if g:
        print("#endif")
print('    default: return "other";')
print("  }")
print("}")
print("#endif")
