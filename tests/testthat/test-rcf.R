test_that("real closed field numbers are exact", {
  ctx <- z3_context()
  two <- z3_rcf(ctx, 2)
  zero <- z3_rcf(ctx, 0)
  one <- z3_rcf(ctx, 1)
  roots <- z3_rcf_roots(list(-two, zero, one))
  expect_length(roots, 2L)
  expect_true(roots[[2]]^2 == two)
  expect_true(roots[[1]] < zero)
  expect_match(z3_rcf_decimal(roots[[2]], 10), "^1\\.4142135623")
  expect_true(z3_rcf_pi(ctx) > z3_rcf(ctx, "314159/100000"))
  expect_true(z3_rcf_pi(ctx) < z3_rcf(ctx, "314160/100000"))
  expect_true(z3_rcf_e(ctx) > z3_rcf(ctx, "27/10"))
  eps <- z3_rcf_infinitesimal(ctx)
  expect_true(eps > zero)
  expect_true(eps < z3_rcf(ctx, "1/1000000000"))
  expect_true(z3_rcf(ctx, "1/3") + z3_rcf(ctx, "1/6") == z3_rcf(ctx, "1/2"))
  expect_identical(format(z3_rcf(ctx, "6/4")), "3/2")
  fr <- z3_rcf_fraction(z3_rcf(ctx, "6/4"))
  expect_identical(c(format(fr$numerator), format(fr$denominator)), c("3", "2"))
  expect_true(two^-1 == z3_rcf(ctx, "1/2"))
  expect_true(-two == z3_rcf(ctx, -2))
  expect_true(two * 3 == z3_rcf(ctx, 6))
  expect_error(z3_rcf(ctx, 0.5), "whole numbers")
  expect_error(z3_rcf(ctx, "1.5"), "rational")
  expect_error(two & two, "not defined")
  skip_if_not(z3_version_at_least("4.12.3"))
  info <- z3_rcf_info(roots[[2]])
  expect_identical(info$kind, "algebraic")
  expect_true(all(c("coefficients", "interval", "sign_conditions") %in% names(info)))
  expect_identical(z3_rcf_info(z3_rcf_pi(ctx))$kind, "transcendental")
  expect_identical(z3_rcf_info(two)$kind, "rational")
})

test_that("algebraic number arithmetic", {
  ctx <- z3_context()
  two <- z3_real_val(ctx, 2)
  r <- z3_algebraic_root(two, 2)
  expect_identical(z3_value(z3_algebraic("*", r, r)), 2)
  expect_true(z3_algebraic("<", r, z3_real_val(ctx, "1.5")))
  expect_false(z3_algebraic("==", r, 1))
  expect_identical(z3_algebraic_sign(r), 1L)
  expect_identical(z3_value(z3_algebraic_power(r, 4)), 4)
  poly <- z3_algebraic_poly(r)
  expect_identical(vapply(poly$coefficients, z3_value, 0), c(-2, 0, 1))
  v0 <- z3_bound_var(ctx, 0, z3_real_sort(ctx))
  roots <- z3_algebraic_roots(v0 * v0 - 2)
  expect_length(roots, 2L)

  expect_error(z3_algebraic("+", z3_real(ctx, "y"), 1), "numeral")
  p <- z3_real(ctx, "p")
  expect_type(z3_subresultants(p^2 - 1, p - 1, p), "list")
})
