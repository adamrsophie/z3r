test_that("symcompR expressions translate to Z3 and back", {
  skip_if_not_installed("symcompR")
  ctx <- z3_context()
  x <- symcompR::Symbol("x", integer = TRUE)
  y <- symcompR::Symbol("y", integer = TRUE)
  e <- z3_from_symbolic(ctx, symcompR::Eq(x^2 + y^2, 25))
  s <- z3_solver(ctx)
  z3_add(s, e, z3_int(ctx, "x") > 3, z3_int(ctx, "y") > 0)
  expect_identical(z3_check(s), "sat")
  v <- z3_model_values(z3_model(s))
  expect_identical(c(v$x, v$y), c(4, 3))
  r <- symcompR::Symbol("r", real = TRUE)
  er <- z3_from_symbolic(ctx, symcompR::Lt(r / 3 + symcompR::Rational(1, 6), 1))
  expect_identical(z3_sort_kind(er), "bool")
  # Mod follows Python's sign convention, which differs from Z3's mod.
  m <- z3_from_symbolic(ctx, x %% -3)
  expect_identical(z3_value(z3_simplify(z3_substitute(m, z3_int(ctx, "x"), 7))), 7 %% -3)
  expect_error(z3_from_symbolic(ctx, symcompR::Float(0.5) + x), "inexact")
  expect_error(z3_from_symbolic(ctx, symcompR::Symbol("z") + 1), "cannot tell the sort")
  expect_error(z3_from_symbolic(ctx, sin(x)), "no exact Z3 translation")
  b <- z3_from_symbolic(ctx, symcompR::And(symcompR::Symbol("p"), symcompR::Not(symcompR::Symbol("q"))))
  st <- z3_solver(ctx)
  z3_add(st, b != z3_and(z3_bool(ctx, "p"), !z3_bool(ctx, "q")))
  expect_identical(z3_check(st), "unsat")
  # Z3 -> symcompR -> Z3 round trip preserves meaning
  zx <- z3_int(ctx, "x")
  zy <- z3_int(ctx, "y")
  for (t in list(zx * 2 + 1, zx %/% -3, zx %% -3, zx - zy, -zx, z3_and(zx > 1, zy <= 2), z3_ite(zx > 0, zx, -zx))) {
    back <- z3_from_symbolic(ctx, z3_to_symbolic(t))
    st <- z3_solver(ctx)
    z3_add(st, back != t)
    expect_identical(z3_check(st), "unsat")
  }
  expect_identical(format(z3_to_symbolic(z3_real_val(ctx, "1/3"))), "1/3")
  expect_error(z3_to_symbolic(z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))(zx)), "uninterpreted")
})
