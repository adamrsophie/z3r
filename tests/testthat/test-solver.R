test_that("the README example solves", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  s <- z3_solver(ctx)
  z3_add(s, x + y == 10)
  expect_identical(z3_check(s), "sat")
  m <- z3_model(s)
  expect_identical(z3_value(z3_eval(m, x + y)), 10)
