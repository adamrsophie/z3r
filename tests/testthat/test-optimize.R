test_that("objective handles are refused after their scope is popped", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  o <- z3_optimize(ctx)
  z3_add(o, x <= 10, x >= 0)
  z3_push(o)
  h1 <- z3_maximize(o, x)
  z3_pop(o)
  h2 <- z3_minimize(o, x)
  expect_identical(z3_check(o), "sat")
  expect_error(z3_optimum(h1), "removed by z3_pop")
  expect_identical(z3_value(z3_optimum(h2)$value), 0)
})

test_that("popping an optimizer needs an open scope", {
  ctx <- z3_context()
  o <- z3_optimize(ctx)
  expect_error(z3_pop(o), "no open scope")
  z3_push(o)
  expect_no_error(z3_pop(o))
})

test_that("soft constraint groups have objective handles", {
  ctx <- z3_context()
  p <- z3_bools(ctx, c("a", "b", "c"))
  opt <- z3_optimize(ctx)
  z3_add(opt, z3_or(!p$a, !p$b), z3_or(!p$b, !p$c))
  z3_add_soft(opt, p$a, 2)
  h <- z3_add_soft(opt, p$b, 3)
  z3_add_soft(opt, p$c, 2)
  expect_s3_class(h, "z3_objective")
  expect_identical(z3_check(opt), "sat")
  # Keeping b violates a and c (weight 4); dropping b costs 3.
  expect_identical(z3_value(z3_optimum(h)$value), 3)
})

