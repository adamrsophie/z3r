test_that("tracked assertions explain contradictions", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x > 0)
  z3_assert_and_track(s, x > 10, "lower")
  z3_assert_and_track(s, x < 5, "upper")
  z3_assert_and_track(s, x != 7, "not_seven")
  expect_identical(z3_check(s), "unsat")
  core <- z3_unsat_core(s)
  expect_setequal(names(core), c("lower", "upper"))
  expect_true(all(vapply(core, z3_is_expr, TRUE)))
  # The core is itself unsatisfiable with the untracked assertions.
  s2 <- z3_solver(ctx)
  z3_add(s2, x > 0, x > 10, x < 5)
  expect_identical(z3_check(s2), "unsat")
})

test_that("cores of assumptions", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  a <- z3_bools(ctx, c("a1", "a2", "a3"))
  s <- z3_solver(ctx)
  z3_add(s, z3_implies(a$a1, x > 5), z3_implies(a$a2, x < 3), z3_implies(a$a3, x == 4))
  expect_identical(z3_check(s, a$a1, a$a3), "unsat")
  expect_setequal(names(z3_unsat_core(s)), c("a1", "a3"))
  expect_identical(z3_check(s, a$a1), "sat")
  expect_error(z3_unsat_core(s), "last result was \"sat\"")
  expect_identical(z3_check(s, a$a1, a$a2), "unsat")
  core <- z3_unsat_core(s)
  expect_setequal(names(core), c("a1", "a2"))
})

test_that("a core without tracking is empty, and stale cores are refused", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x > 0, x < 0)
  expect_identical(z3_check(s), "unsat")
  expect_length(z3_unsat_core(s), 0L)
  z3_add(s, x == 1)
  expect_error(z3_unsat_core(s), "changed")
  expect_error(z3_unsat_core(z3_solver(ctx)), "call z3_check")
})

test_that("tracked labels may be given as expressions", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  lab <- z3_bool(ctx, "my_label")
  s <- z3_solver(ctx)
  z3_assert_and_track(s, x > 1, lab)
  z3_assert_and_track(s, x < 1, "other")
  expect_identical(z3_check(s), "unsat")
  expect_setequal(names(z3_unsat_core(s)), c("my_label", "other"))
  expect_error(z3_assert_and_track(s, x, "bad"), "Boolean")
  expect_error(z3_assert_and_track(s, x > 0, x), "Boolean")
})
