test_that("expression trees can be inspected", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  e <- x + 2 * y
  expect_identical(z3_kind(e), "app")
  expect_identical(z3_kind(z3_int_val(ctx, 3)), "numeral")
  info <- z3_decl_info(z3_decl(e))
  expect_identical(info$name, "+")
  expect_identical(info$kind, "add")
  expect_true(info$interpreted)
  expect_length(z3_args(e), 2L)
  expect_true(z3_identical(z3_args(e)[[1]], x))
  expect_identical(z3_num_args(x), 0L)
  expect_true(z3_is_const(x))
  expect_false(z3_is_const(x + 1))
  expect_true(z3_is_numeral(z3_real_val(ctx, "1/2")))
  expect_true(z3_is_app(e))
  kinds <- vapply(list(x <= y, x %/% y, x %% y, -x, x * y, x - y, z3_ite(x > 0, x, y)),
                  function(t) z3_decl_info(z3_decl(t))$kind, "")
  expect_identical(kinds, c("le", "idiv", "mod", "uminus", "mul", "sub", "ite"))
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  fi <- z3_decl_info(f)
  expect_identical(fi$kind, "uninterpreted")
  expect_false(fi$interpreted)
  expect_identical(format(fi$range), "Int")
  ex <- z3_decl_info(z3_decl(z3_extract(z3_bv(ctx, "b", 8), 5, 2)))
  expect_identical(ex$parameters, list(5L, 2L))
  expect_error(z3_args(z3_forall(x, x > 0)), "not an application")
})

test_that("quantifiers can be taken apart", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  q <- z3_forall(list(x, y), x + y == y + x, weight = 2, qid = "comm")
  info <- z3_quantifier_info(q)
  expect_identical(info$type, "forall")
  expect_identical(info$names, c("x", "y"))
  expect_identical(info$weight, 2L)
  expect_true(z3_is_quantifier(q))
  body <- info$body
  vars <- z3_args(z3_args(body)[[1]])
  expect_identical(vapply(vars, z3_kind, ""), c("var", "var"))
  expect_setequal(vapply(vars, z3_var_index, 0L), c(0L, 1L))
  expect_identical(z3_quantifier_info(z3_exists(x, x > 0))$type, "exists")
  expect_identical(z3_quantifier_info(z3_lambda(x, x + 1))$type, "lambda")
  expect_error(z3_var_index(x), "not a bound variable")
})

test_that("substitution replaces terms, variables and functions", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  expect_identical(format(z3_substitute(x + y, x, 3)), "(+ 3 y)")
  expect_identical(z3_value(z3_simplify(z3_substitute(x * y, list(x, y), list(2, 5)))), 10)
  expect_error(z3_substitute(x, list(x, y), list(1)), "same length")
  expect_error(z3_substitute(x, x, TRUE), "different sort")
  v0 <- z3_bound_var(ctx, 0, z3_int_sort(ctx))
  expect_identical(format(z3_substitute_vars(v0 + 1, list(y))), "(+ y 1)")
  skip_if_not(z3_version_at_least("4.9.0"))
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  g <- z3_substitute_funs(f(x) + f(2), f, v0 * v0)
  expect_identical(z3_value(z3_simplify(z3_substitute(g, x, 3))), 13)
})

test_that("translation copies objects between contexts", {
  a <- z3_context()
  b <- z3_context()
  x <- z3_int(a, "x")
  e <- z3_translate(x + 1, b)
  expect_true(z3_same_context(e, b))
  expect_identical(format(e), "(+ x 1)")
  s <- z3_solver(a)
  z3_add(s, x > 5, x < 7)
  s2 <- z3_translate(s, b)
  expect_identical(z3_check(s2), "sat")
  expect_identical(z3_value(z3_eval(z3_model(s2), z3_int(b, "x"))), 6)
  z3_check(s)
  m2 <- z3_translate(z3_model(s), b)
  expect_identical(z3_value(z3_eval(m2, z3_int(b, "x"))), 6)
  g <- z3_goal(a)
  z3_add(g, x > 1)
  expect_true(z3_same_context(z3_translate(g, b), b))
  expect_error(z3_translate(1, b), "must be")
})

test_that("ids, hashes and structural predicates", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  expect_identical(z3_ast_id(x + 1), z3_ast_id(x + 1))
  expect_false(z3_ast_id(x + 1) == z3_ast_id(x + 2))
  expect_type(z3_ast_hash(x), "double")
  expect_true(z3_is_well_sorted(x + 1))
  skip_if_not(z3_version_at_least("4.14.0"))
  expect_true(z3_is_ground(x + 1))
  expect_false(z3_is_ground(z3_bound_var(ctx, 0, z3_int_sort(ctx))))
  expect_identical(z3_depth(x + 2 * x), 3L)
})

test_that("simplifier parameters, print modes and context configuration", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  expect_identical(format(z3_simplify((x + 1) * (x + 1), som = TRUE)), "(+ 1 (* 2 x) (* x x))")
  expect_error(z3_simplify(x, nonsense = TRUE), "unknown parameter")
  expect_true("som" %in% z3_simplify_help(ctx)$name)
  z3_set_print_mode(ctx, "low_level")
  expect_type(format(x + 1), "character")
  z3_set_print_mode(ctx, "smtlib2")
  expect_identical(format(x + 1), "(+ x 1)")
  expect_error(z3_set_print_mode(ctx, "fancy"))
  expect_error(z3_context(bogus = 1), "unknown context parameter")
  expect_error(z3_context(TRUE), "must be named")
  pctx <- z3_context(proof = TRUE, unsat_core = TRUE)
  expect_s3_class(pctx, "z3_context")
})

test_that("global parameters round trip", {
  old <- z3_global_param_get("verbose")
  on.exit(z3_global_param_set("verbose", old))
  z3_global_param_set("verbose", 0)
  expect_identical(z3_global_param_get("verbose"), "0")
  expect_error(z3_global_param_set("no.such.param", 1), "unknown global parameter")
  expect_true(is.na(z3_global_param_get("no.such.param")))
  if (!z3_version_at_least("4.15.0")) {
    expect_error(z3_global_param_help(z3_context()), "4.15.0")
    skip("z3_global_param_help() needs Z3 4.15.0")
  }
  expect_gt(nrow(z3_global_param_help(z3_context())), 10)
  # The list is a copy: releasing it leaves Z3's own table intact.
  gc()
  expect_s3_class(z3_context(), "z3_context")
  expect_identical(z3_global_param_get("verbose"), "0")
})

