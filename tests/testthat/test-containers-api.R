test_that("function entries keep the arity of their interpretation", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  g <- z3_function(ctx, "g", list(I, I), I)
  m <- z3_model(ctx)
  z3_model_set_function(m, g, list(list(args = list(1, 2), value = 3)), 0)
  e <- z3_model_functions(m)$g$entries
  expect_length(e, 1L)
  expect_length(e[[1]]$args, 2L)
  expect_identical(z3_value(z3_eval(m, g(1, 2))), 3)
})

test_that("default values of function interpretations can be replaced", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", I, I)
  m <- z3_model(ctx)
  z3_model_set_function(m, f, list(list(args = list(5), value = 50)), 0)
  expect_invisible(z3_model_set_default(m, f, 9))
  fi <- z3_model_functions(m)$f
  expect_identical(z3_value(fi$`else`), 9)
  expect_length(fi$entries, 1L)
  expect_identical(z3_value(z3_eval(m, f(5))), 50)
  expect_identical(z3_value(z3_eval(m, f(6))), 9)
  z3_model_set_default(m, f, z3_bound_var(ctx, 0, I) + 1)
  expect_identical(z3_value(z3_eval(m, f(7))), 8)
  expect_error(z3_model_set_default(m, f, z3_bound_var(ctx, 1, I)), "bound variable 1")
  expect_error(z3_model_set_default(m, f, TRUE), "wrong sort")
  h <- z3_function(ctx, "h", I, I)
  expect_error(z3_model_set_default(m, h, 0), "no interpretation")
  expect_error(z3_model_set_default(m, z3_int(ctx, "k"), 0), "no arguments")
})

test_that("changing a model updates values already evaluated", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  x <- z3_int(ctx, "x")
  f <- z3_function(ctx, "f", I, I)
  m <- z3_model(ctx)
  z3_model_set(m, x, 1)
  z3_model_set_function(m, f, list(), 0)
  t <- (x + 1) * 2 + f(x + 1)
  expect_identical(z3_value(z3_eval(m, t)), 4)
  z3_model_set(m, x, 10)
  expect_identical(z3_value(z3_eval(m, t)), 22)
  z3_model_set_default(m, f, 5)
  expect_identical(z3_value(z3_eval(m, t)), 27)
})

test_that("R whole numbers make real closed field integers", {
  ctx <- z3_context()
  expect_true(z3_rcf(ctx, 7L) == z3_rcf(ctx, "7"))
  expect_true(z3_rcf(ctx, -3) == z3_rcf(ctx, "-3"))
  expect_true(z3_rcf(ctx, 0) == z3_rcf(ctx, "0"))
  big <- 2^40
  expect_true(z3_rcf(ctx, big) == z3_rcf(ctx, "1099511627776"))
  expect_true(z3_rcf(ctx, 2) * z3_rcf(ctx, "1/2") == 1)
  expect_error(z3_rcf(ctx, NA_integer_), "whole numbers")
})
