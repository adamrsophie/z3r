test_that("probes measure goals and compose", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  g <- z3_goal(ctx)
  z3_add(g, x > 0, x + y < 10)
  expect_identical(z3_probe_apply(z3_probe(ctx, "num-consts"), g), 2)
  expect_identical(z3_probe_apply(z3_probe(ctx, "size"), g), 2)
  expect_identical(z3_probe_apply(z3_probe(ctx, "size") < 5, g), 1)
  expect_identical(z3_probe_apply(z3_probe(ctx, "size") > 5, g), 0)
  expect_identical(z3_probe_apply(!(z3_probe(ctx, "size") > 5), g), 1)
  expect_identical(z3_probe_apply(z3_probe(ctx, "size") != 2, g), 0)
  both <- (z3_probe(ctx, "size") >= 2) & (z3_probe(ctx, "num-consts") == 2)
  expect_identical(z3_probe_apply(both, g), 1)
  expect_true("is-qflia" %in% z3_probes(ctx)$name)
  expect_error(z3_probe(ctx, "no-such-probe"), "Z3 error")
})

test_that("conditional, parallel and parameterized tactics", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  g <- z3_goal(ctx)
  z3_add(g, x > 0, x < 0)
  small <- z3_probe(ctx, "size") < 5
  t <- z3_tactic_cond(small, z3_tactic(ctx, "smt"), z3_tactic_skip(ctx))
  expect_identical(z3_goal_status(z3_apply_tactic(t, g)[[1]]), "unsat")
  expect_error(z3_apply_tactic(z3_tactic_fail(ctx), g), "Z3 error")
  expect_error(z3_apply_tactic(z3_tactic_fail_if(small), g), "Z3 error")
  expect_length(z3_apply_tactic(z3_tactic_when(!small, z3_tactic(ctx, "smt")), g), 1L)
  po <- z3_tactic_par_or(z3_tactic(ctx, "smt"), z3_tactic_skip(ctx))
  expect_length(z3_apply_tactic(po, g), 1L)
  pt <- z3_tactic_par_then(z3_tactic(ctx, "simplify"), z3_tactic(ctx, "smt"))
  expect_identical(z3_goal_status(z3_apply_tactic(pt, g)[[1]]), "unsat")
  g2 <- z3_goal(ctx)
  z3_add(g2, (x + 1) * (x + 1) > 0)
  tw <- z3_tactic_with(z3_tactic(ctx, "simplify"), som = TRUE)
  expect_match(format(z3_goal_formulas(z3_apply_tactic(tw, g2)[[1]])[[1]]), "\\* x x")
  expect_true("som" %in% z3_tactic_params(z3_tactic(ctx, "simplify"))$name)
  expect_error(z3_apply_tactic(z3_tactic_fail_if_not_decided(ctx), g2), "Z3 error")
})

test_that("goal information and model conversion", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  g <- z3_goal(ctx)
  z3_add(g, x == y + 1, y > 2)
  info <- z3_goal_info(g)
  expect_identical(info$size, 2L)
  expect_identical(info$precision, "precise")
  expect_false(info$inconsistent)
  sub <- z3_apply_tactic(z3_tactic(ctx, "solve-eqs"), g)[[1]]
  s <- z3_solver(ctx)
  z3_add(s, z3_goal_formulas(sub))
  expect_identical(z3_check(s), "sat")
  m <- z3_goal_convert_model(sub, z3_model(s))
  expect_identical(z3_value(z3_eval(m, x)) - z3_value(z3_eval(m, y)), 1)
  z3_goal_reset(g)
  expect_identical(z3_goal_info(g)$size, 0L)
})

test_that("simplifiers preprocess incremental solvers", {
  skip_if_not(z3_version_at_least("4.12.2"))
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  simp <- z3_simplifier_then(z3_simplifier(ctx, "solve-eqs"), z3_simplifier(ctx, "elim-unconstrained"))
  s <- z3_solver_add_simplifier(z3_solver(ctx), simp)
  z3_add(s, x == y + 2, y > 3)
  expect_identical(z3_check(s), "sat")
  m <- z3_model(s)
  expect_identical(z3_value(z3_eval(m, x)) - z3_value(z3_eval(m, y)), 2)
  expect_true("solve-eqs" %in% z3_simplifiers(ctx)$name)
  expect_type(z3_help(z3_simplifier(ctx, "solve-eqs")), "character")
  expect_s3_class(z3_simplifier_with(z3_simplifier(ctx, "solve-eqs"), theory_solver = FALSE), "z3_simplifier")
})
