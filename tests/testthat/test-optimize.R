test_that("linear optimization finds the optimum", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  opt <- z3_optimize(ctx)
  z3_add(opt, x >= 0, y >= 0, x + 2 * y <= 14, 3 * x - y >= 0, x - y <= 2)
  obj <- z3_maximize(opt, 3 * x + 4 * y)
  expect_identical(z3_check(opt), "sat")
  o <- z3_optimum(obj)
  expect_identical(o$status, "optimal")
  expect_identical(z3_value(o$value), 34)
  m <- z3_model(opt)
  expect_identical(z3_value(z3_eval(m, 3 * x + 4 * y)), 34)
  # Brute-force check of the integer optimum
  best <- max(apply(expand.grid(x = 0:14, y = 0:7), 1, function(p) {
    if (p[1] + 2 * p[2] <= 14 && 3 * p[1] - p[2] >= 0 && p[1] - p[2] <= 2) 3 * p[1] + 4 * p[2] else -Inf
  }))
  expect_identical(best, 34)
})

test_that("minimization over the reals is exact", {
  ctx <- z3_context()
  r <- z3_real(ctx, "r")
  opt <- z3_optimize(ctx)
  z3_add(opt, 3 * r >= 1)
  obj <- z3_minimize(opt, r)
  expect_identical(z3_check(opt), "sat")
  o <- z3_optimum(obj)
  expect_identical(o$status, "optimal")
  expect_identical(format(o$value), "(/ 1.0 3.0)")
})

test_that("unbounded and unattained optima are reported", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  o1 <- z3_optimize(ctx)
  z3_add(o1, x >= 0)
  h1 <- z3_maximize(o1, x)
  expect_identical(z3_check(o1), "sat")
  expect_identical(z3_optimum(h1)$status, "unbounded")
  expect_null(z3_optimum(h1)$value)
  expect_output(print(z3_optimum(h1)), "\\+oo")
  o2 <- z3_optimize(ctx)
  z3_add(o2, r < 3)
  h2 <- z3_maximize(o2, r)
  expect_identical(z3_check(o2), "sat")
  res <- z3_optimum(h2)
  # Z3 4.8.13 (its own command line tool too) reports the strict bound
  # r < 3 as attained at 2; Z3 4.10.2 and later report the supremum.
  if (z3_version_at_least("4.10.0")) {
    expect_identical(res$status, "not attained")
    expect_identical(z3_value(res$value), 3)
    expect_match(res$upper, "^3(\\.0)? - epsilon$")
  }
  o3 <- z3_optimize(ctx)
  z3_add(o3, x <= 5)
  h3 <- z3_minimize(o3, x)
  z3_check(o3)
  expect_identical(z3_optimum(h3)$lower, "-oo")
})

test_that("soft constraints minimize the violated weight", {
  ctx <- z3_context()
  p <- z3_bools(ctx, c("a", "b", "c"))
  opt <- z3_optimize(ctx)
  z3_add(opt, z3_or(!p$a, !p$b), z3_or(!p$b, !p$c))
  z3_add_soft(opt, p$a, 2)
  z3_add_soft(opt, p$b, 3)
  z3_add_soft(opt, p$c, 2.5)
  expect_identical(z3_check(opt), "sat")
  v <- z3_model_values(z3_model(opt))
  expect_identical(v[c("a", "b", "c")], list(a = TRUE, b = FALSE, c = TRUE))
  expect_error(z3_add_soft(opt, p$a, -1), "positive")
  expect_error(z3_add_soft(opt, p$a, "abc"), "positive decimal")
  expect_error(z3_add_soft(opt, z3_int(ctx, "x"), 1), "Boolean")
})

test_that("lexicographic and box priorities", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  lex <- z3_optimize(ctx)
  z3_add(lex, x + y <= 10, x >= 0, y >= 0, x <= 7, y <= 7)
  h1 <- z3_maximize(lex, x)
  h2 <- z3_maximize(lex, y)
  z3_check(lex)
  expect_identical(z3_value(z3_optimum(h1)$value), 7)
  expect_identical(z3_value(z3_optimum(h2)$value), 3)
  box <- z3_optimize(ctx, priority = "box")
  z3_add(box, x + y <= 10, x >= 0, y >= 0, x <= 7, y <= 7)
  b1 <- z3_maximize(box, x)
  b2 <- z3_maximize(box, y)
  z3_check(box)
  expect_identical(z3_value(z3_optimum(b1)$value), 7)
  expect_identical(z3_value(z3_optimum(b2)$value), 7)
})

test_that("optimizer state rules match the solver", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  opt <- z3_optimize(ctx)
  expect_error(z3_model(opt), "call z3_check")
  z3_add(opt, x > 0, x < 0)
  expect_identical(z3_check(opt), "unsat")
  expect_error(z3_model(opt), "last result was \"unsat\"")
  opt2 <- z3_optimize(ctx)
  z3_add(opt2, x >= 1, x <= 3)
  h <- z3_minimize(opt2, x)
  z3_check(opt2)
  z3_add(opt2, x >= 2)
  expect_error(z3_optimum(h), "changed")
  z3_check(opt2)
  expect_identical(z3_value(z3_optimum(h)$value), 2)
  z3_push(opt2)
  z3_add(opt2, x >= 3)
  z3_check(opt2)
  expect_identical(z3_value(z3_optimum(h)$value), 3)
  z3_pop(opt2)
  z3_check(opt2)
  expect_identical(z3_value(z3_optimum(h)$value), 2)
  expect_output(print(opt2), "z3_optimize")
  expect_type(z3_statistics(opt2), "list")
  expect_true("priority" %in% z3_param_help(opt2)$name)
  expect_error(z3_minimize(opt2, x > 0), "Int, Real or bit-vector")
})

