test_that("cardinality and pseudo-Boolean constraints", {
  ctx <- z3_context()
  p <- z3_bools(ctx, letters[1:4])
  v <- unlist(solve_values(ctx, z3_atleast(p, k = 3), z3_pble(p, c(1, 2, 3, 4), 6), vars = p))
  expect_gte(sum(v), 3)
  expect_lte(sum(c(1, 2, 3, 4)[v]), 6)
  expect_identical(check_status(ctx, z3_pbeq(p, c(2, 2, 2, 2), 3)), "unsat")
  expect_identical(check_status(ctx, z3_atmost(p, k = 1), p$a, p$b), "unsat")
  expect_identical(check_status(ctx, z3_pbge(p, c(1, 1, 1, 1), 4), !p$a), "unsat")
  expect_error(z3_pble(p, c(1, 2), 1), "one coefficient")
  expect_error(z3_pble(p, c(1.5, 2, 3, 4), 1), "whole numbers")
})

test_that("recursive functions unfold", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  fact <- z3_rec_function(ctx, "fact", I, I)
  n <- z3_int(ctx, "n")
  z3_rec_define(fact, n, z3_ite(n <= 0, 1, n * fact(n - 1)))
  # Unfolding need not terminate: Z3 4.8.13 runs fact(x) == 120 without
  # end. CI shows termination from Z3 4.13.3, so older releases may give up.
  unfolded <- function(goal, var) {
    s <- z3_solver(ctx)
    z3_add(s, goal)
    status <- z3_check(s, timeout = 20000)
    if (status == "unknown" && !z3_version_at_least("4.13.0")) {
      skip(paste("Z3", z3_version()$runtime, "does not unfold this definition in time"))
    }
    expect_identical(status, "sat")
    z3_value(z3_eval(z3_model(s), var))
  }
  x <- z3_int(ctx, "x")
  expect_identical(unfolded(fact(x) == 120, x), 5)
  fib <- z3_rec_function(ctx, "fib", I, I)
  z3_rec_define(fib, n, z3_ite(n <= 1, n, fib(n - 1) + fib(n - 2)))
  y <- z3_int(ctx, "y")
  expect_identical(unfolded(y == fib(10), y), 55)
  expect_error(z3_rec_define(fib, list(n, x), n), "one parameter")
  expect_s3_class(z3_fresh_function(ctx, "g", I, I), "z3_function")
})

test_that("special relations", {
  ctx <- z3_context()
  U <- z3_uninterpreted_sort(ctx, "U")
  a <- z3_const(ctx, "a", U)
  b <- z3_const(ctx, "b", U)
  cc <- z3_const(ctx, "c", U)
  le <- z3_partial_order(U)
  expect_identical(check_status(ctx, le(a, b), le(b, a), a != b), "unsat")
  expect_identical(check_status(ctx, le(a, b), le(b, cc), !le(a, cc)), "unsat")
  lo <- z3_linear_order(U)
  expect_identical(check_status(ctx, !lo(a, b), !lo(b, a)), "unsat")
  expect_s3_class(z3_tree_order(U), "z3_function")
  expect_s3_class(z3_piecewise_linear_order(U), "z3_function")
  R <- z3_function(ctx, "R", list(U, U), z3_bool_sort(ctx))
  tc <- z3_transitive_closure(R)
  expect_identical(check_status(ctx, R(a, b), R(b, cc), !tc(a, cc)), "unsat")
})

test_that("divisibility, bit tests, finite domains and quantifier options", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  expect_identical(solve_values(ctx, z3_divides(7, x), x > 50, x < 60, vars = list(x))[[1]], 56)
  expect_identical(check_status(ctx, !z3_bvneg_no_overflow(z3_bv(ctx, "b", 8))), "sat")
  expect_identical(z3_finite_domain_size(z3_finite_domain_sort(ctx, "FD", 12)), 12)
  q <- z3_forall(x, x * 0 == 0, weight = 3, qid = "q1", skid = "sk")
  expect_identical(z3_quantifier_info(q)$weight, 3L)
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  q2 <- z3_forall(x, f(x) > 0, no_patterns = list(f(x)))
  expect_identical(z3_sort_kind(q2), "bool")
  skip_if_not(z3_version_at_least("4.8.16"))
  expect_true(z3_value(z3_simplify(z3_bit2bool(z3_bv_val(ctx, 4, 8), 2))))
  expect_error(z3_bit2bool(z3_bv_val(ctx, 4, 8), 8), "between")
})
