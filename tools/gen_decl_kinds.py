"""Generate src/decl_kinds.h from Z3 C API headers.

Usage: python3 tools/gen_decl_kinds.py z3_api.h [z3_api.h ...] > src/decl_kinds.h

Only enumerators of Z3_decl_kind present in every given header are listed, so
the generated switch compiles against each of those Z3 versions. Pass the
headers of the oldest supported release and the newest ones tested.
"""
import re
import sys


def ops(path):
    text = open(path).read()
    body = re.search(r"typedef enum \{(.*?)\} Z3_decl_kind;", text, re.S).group(1)
    return set(re.findall(r"\b(Z3_OP_[A-Z0-9_]+)\b", body))


common = set.intersection(*(ops(p) for p in sys.argv[1:]))
print("// Generated by tools/gen_decl_kinds.py; do not edit by hand.")
print("// Names of Z3_decl_kind values common to all supported Z3 versions.")
print("#ifndef Z3R_DECL_KINDS_H")
print("#define Z3R_DECL_KINDS_H")
print("inline const char* decl_kind_name(Z3_decl_kind k) {")
print("  switch (k) {")
for name in sorted(common):
    print(f'    case {name}: return "{name[6:].lower()}";')
print('    default: return "other";')
print("  }")
print("}")
print("#endif")
