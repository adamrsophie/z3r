test_that("complex numbers", {
  skip_if_not(z3_version_at_least("5.3.2"))
  ctx <- z3_context()
  z <- z3_const(ctx, "z", z3_complex_sort(ctx))
  expect_identical(z3_sort_kind(z), "complex")
  s <- z3_solver(ctx)
  z3_add(s, z3_real_part(z) == 3, z3_imag_part(z) == -4)
  expect_identical(z3_check(s), "sat")
  expect_identical(format(z3_eval(z3_model(s), z)), "(complex.make 3.0 (- 4.0))")
  expect_identical(format(z3_complex(z3_real_val(ctx, 1), 2)), "(complex.make 1.0 2.0)")
})

test_that("finite fields", {
  skip_if_not(z3_version_at_least("5.3.0"))
  ctx <- z3_context()
  F7 <- z3_ff_sort(ctx, 7)
  expect_identical(z3_ff_size(F7), "7")
  f <- z3_const(ctx, "f", F7)
  s <- z3_solver(ctx)
  z3_add(s, z3_ff_mul(f, f) == z3_val(ctx, 2, F7))
  expect_identical(z3_check(s), "sat")
  root <- z3_eval(z3_model(s), f)
  expect_true(format(root) %in% c("#f3m7", "#f4m7", "3", "4") || z3_kind(root) == "numeral")
  s2 <- z3_solver(ctx)
  z3_add(s2, z3_ff_mul(f, f) == z3_val(ctx, 3, F7))
  expect_identical(z3_check(s2), "unsat")
})

test_that("finite sets", {
  skip_if_not(z3_version_at_least("5.0.0"))
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  fs <- z3_const(ctx, "fs", z3_finite_set_sort(I))
  expect_true(z3_fs_element_sort(z3_finite_set_sort(I)) == I)
  s <- z3_solver(ctx)
  z3_add(s, z3_fs_member(1, fs), z3_fs_member(3, fs))
  expect_identical(z3_check(s), "sat")
  s2 <- z3_solver(ctx)
  z3_add(s2, z3_fs_member(1, fs), !z3_fs_member(1, z3_fs_union(fs, z3_fs_singleton(z3_int_val(ctx, 2)))))
  expect_identical(z3_check(s2), "unsat")
  expect_s3_class(z3_fs_empty(z3_finite_set_sort(I)), "z3_expr")
  expect_s3_class(z3_fs_size(fs), "z3_expr")
})
