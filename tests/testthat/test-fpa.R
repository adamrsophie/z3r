test_that("floating point arithmetic matches IEEE doubles", {
  ctx <- z3_context()
  D <- z3_fp64_sort(ctx)
  fv <- function(v) z3_fp_val(ctx, v, D)
  val <- function(e) z3_value(z3_simplify(e))
  expect_identical(val(fv(0.1) + fv(0.2)), 0.1 + 0.2)
  expect_false(val(fv(0.1) + fv(0.2)) == 0.3)
  for (a in c(1.5, -2.25, 1e300, 3e-310, 0.1)) for (b in c(3, -0.5, 7e-3)) {
    expect_identical(val(fv(a) * fv(b)), a * b)
    expect_identical(val(fv(a) / fv(b)), a / b)
    expect_identical(val(fv(a) - fv(b)), a - b)
  }
  expect_identical(val(fv(1e308) * fv(10)), Inf)
  expect_true(is.nan(val(fv(0) / fv(0))))
  expect_identical(1 / val(z3_fp_zero(D, negative = TRUE)), -Inf)
  expect_identical(val(-fv(2)), -2)
  expect_identical(val(abs(fv(-3))), 3)
})

test_that("special values, equality and comparisons", {
  ctx <- z3_context()
  D <- z3_fp64_sort(ctx)
  nan <- z3_fp_nan(D)
  val <- function(e) z3_value(z3_simplify(e))
  expect_true(val(nan == nan))
  expect_false(val(z3_fp_eq(nan, nan)))
  expect_false(val(z3_fp_zero(D) == z3_fp_zero(D, negative = TRUE)))
  expect_true(val(z3_fp_eq(z3_fp_zero(D), z3_fp_zero(D, negative = TRUE))))
  expect_false(val(nan < 1))
  expect_true(val(z3_fp_is_nan(nan)))
  expect_true(val(z3_fp_is_infinite(z3_fp_inf(D))))
  expect_true(val(z3_fp_is_negative(z3_fp_inf(D, negative = TRUE))))
  expect_true(val(z3_fp_is_subnormal(z3_fp_val(ctx, 3e-310, D))))
  expect_true(val(z3_fp_is_normal(z3_fp_val(ctx, 1, D))))
  expect_true(val(z3_fp_is_zero(z3_fp_zero(D))))
  expect_true(val(z3_fp_is_positive(z3_fp_val(ctx, 2, D))))
  expect_true(val(z3_fp_lt(z3_fp_val(ctx, 1, D), 2)))
  expect_identical(val(z3_fp_min(z3_fp_val(ctx, 1, D), 2)), 1)
  expect_identical(val(z3_fp_max(z3_fp_val(ctx, 1, D), 2)), 2)
})

test_that("solving over floating point", {
  ctx <- z3_context()
  D <- z3_fp64_sort(ctx)
  x <- z3_fp(ctx, "x", D)
  v <- solve_values(ctx, x + 1 == x, !z3_fp_is_nan(x), x > 0, vars = list(x = x))$x
  expect_true(v + 1 == v)
  # In half precision (small enough to solve quickly), x * x == 2 has a
  # solution only because of rounding; check it by rounding in R as well.
  H <- z3_fp16_sort(ctx)
  h <- z3_fp(ctx, "h", H)
  v2 <- solve_values(ctx, h * h == z3_fp_val(ctx, 2, H), h > 0, vars = list(h = h))$h
  expect_false(v2 * v2 == 2)
  expect_identical(z3_value(z3_simplify(z3_fp_val(ctx, v2, H) * z3_fp_val(ctx, v2, H))), 2)
})

test_that("rounding modes and explicit rounding", {
  ctx <- z3_context()
  D <- z3_fp64_sort(ctx)
  F <- z3_fp32_sort(ctx)
  two <- z3_fp_val(ctx, 2, D)
  up <- z3_value(z3_simplify(z3_fp_sqrt(z3_rounding(ctx, "RTP"), two)))
  down <- z3_value(z3_simplify(z3_fp_sqrt(z3_rounding(ctx, "RTN"), two)))
  expect_true(up > down)
  expect_identical(z3_value(z3_simplify(z3_fp_fma(z3_rounding(ctx), two, 3, 1))), 7)
  expect_identical(z3_value(z3_simplify(z3_fp_round_to_integral(z3_rounding(ctx, "RTZ"), z3_fp_val(ctx, -2.7, D)))), -2)
  expect_identical(z3_value(z3_rounding(ctx, "RTP")), "roundTowardPositive")
  f32 <- z3_fp(ctx, "f32", F)
  expect_error(f32 + 0.1, "not exactly representable")
  # 0.1 rounded to single precision, read back exactly as a double
  f01 <- z3_value(z3_fp_val(ctx, 0.1, F, "RNE"))
  expect_identical(sprintf("%.27f", f01), "0.100000001490116119384765625")
  expect_identical(z3_value(z3_fp_val(ctx, 0.5, F)), 0.5)
  expect_error(z3_rounding(ctx, "UP"))
})

test_that("conversions", {
  ctx <- z3_context()
  D <- z3_fp64_sort(ctx)
  rne <- z3_rounding(ctx)
  val <- function(e, ...) z3_value(z3_simplify(e), ...)
  expect_identical(format(z3_simplify(z3_fp_to_real(z3_fp_val(ctx, 0.75, D)))), "(/ 3.0 4.0)")
  expect_identical(val(z3_fp_to_sbv(rne, z3_fp_val(ctx, -3.7, D), 8), signed = TRUE), -4)
  expect_identical(val(z3_fp_to_ubv(rne, z3_fp_val(ctx, 3.2, D), 8)), 3)
  expect_equal(val(z3_fp_to_fp(rne, z3_real_val(ctx, "1/3"), D)), 1 / 3)
  expect_identical(val(z3_fp_to_fp(rne, z3_int_val(ctx, 5), D)), 5)
  bits <- z3_simplify(z3_fp_to_ieee_bv(z3_fp_val(ctx, 1, D)))
  expect_identical(as.character(z3_value(bits)), "4607182418800017408")
  expect_identical(val(z3_fp_from_bv(bits, D)), 1)
  expect_identical(val(z3_fp_from_signed(rne, z3_bv_val(ctx, -5, 8), D)), -5)
  expect_identical(val(z3_fp_from_unsigned(rne, z3_bv_val(ctx, 251, 8), D)), 251)
  parts <- z3_fp_numeral_parts(z3_fp_val(ctx, 1.5, D))
  expect_identical(parts$class, "normal")
  expect_identical(parts$significand, "1.5")
  expect_identical(unname(z3_fp_sort_info(z3_fp16_sort(ctx))), c(5L, 11L))
  q <- z3_fp_val(ctx, 0.1, z3_fp128_sort(ctx))
  expect_identical(z3_value(q), 0.1)
  third <- z3_simplify(z3_fp_to_fp(rne, z3_real_val(ctx, "1/3"), z3_fp128_sort(ctx)))
  expect_error(z3_value(third), "not exactly representable")
  expect_equal(z3_value(third, exact = FALSE), 1 / 3)
})
