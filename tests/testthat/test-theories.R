test_that("arrays: select, store and extensionality", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  a <- z3_array(ctx, "a", I, I)
  i <- z3_int(ctx, "i")
  j <- z3_int(ctx, "j")
  expect_identical(check_status(ctx, z3_select(z3_store(a, i, 10), i) != 10), "unsat")
  expect_identical(check_status(ctx, i != j, z3_select(z3_store(a, i, 10), j) != z3_select(a, j)), "unsat")
  expect_identical(z3_value(z3_simplify(z3_select(z3_const_array(I, 7), 99))), 7)
  r <- z3_array(ctx, "r", I, z3_real_sort(ctx))
  expect_identical(z3_sort_kind(z3_store(r, 1, 2)), "array")
  expect_error(z3_select(a, z3_bool(ctx, "p")), "index has sort Bool")
  expect_error(z3_store(a, 1, TRUE), "stored value has sort Bool")
  expect_error(z3_select(i, 1), "needs an array")
})

test_that("strings: constraints and functions", {
  ctx <- z3_context()
  s <- z3_string(ctx, "s")
  sol <- z3_solver(ctx)
  z3_add(sol, z3_length(s) == 5, z3_prefixof("ab", s), z3_contains(s, "zz"))
  expect_identical(z3_check(sol), "sat")
  v <- z3_value(z3_eval(z3_model(sol), s))
  expect_identical(nchar(v), 5L)
  expect_true(startsWith(v, "ab"))
  expect_true(grepl("zz", v, fixed = TRUE))
  val <- function(e) z3_value(z3_simplify(e))
  hello <- z3_string_val(ctx, "hello")
  expect_identical(val(z3_concat(hello, " ", "world")), "hello world")
  expect_identical(val(z3_substr(hello, 1, 3)), "ell")
  expect_identical(val(z3_str_at(hello, 4)), "o")
  expect_identical(val(z3_indexof(hello, "l")), 2)
  expect_identical(val(z3_indexof(hello, "z")), -1)
  expect_identical(val(z3_replace(hello, "l", "L")), "heLlo")
  expect_identical(val(z3_str_to_int(z3_string_val(ctx, "123"))), 123)
  expect_identical(val(z3_str_to_int(z3_string_val(ctx, "1a"))), -1)
  expect_identical(val(z3_int_to_str(z3_int_val(ctx, 45))), "45")
  expect_true(val(z3_suffixof("llo", hello)))
  expect_true(val(z3_str_lt("abc", z3_string_val(ctx, "abd"))))
  expect_error(z3_length(z3_int(ctx, "x")), "String")
})

test_that("uninterpreted functions and congruence", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", list(I), I)
  g <- z3_function(ctx, "g", list(I, z3_real_sort(ctx)), z3_bool_sort(ctx))
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  expect_identical(check_status(ctx, x == y, f(x) != f(y)), "unsat")
  expect_identical(check_status(ctx, f(f(x)) == x, f(x) == y, x != y), "sat")
  expect_identical(z3_sort_kind(g(x, 1)), "bool")
  expect_identical(format(g(1, 2)), "(g 1 2.0)")
  expect_error(f(x, y), "takes 1 argument")
  expect_error(f(TRUE), "expects Int")
  expect_output(print(f), "declare-fun f \\(Int\\) Int")
  expect_s3_class(z3_decl(f), "z3_func_decl")
  u <- z3_uninterpreted_sort(ctx, "U")
  h <- z3_function(ctx, "h", u, u)
  a <- z3_const(ctx, "a", u)
  expect_identical(check_status(ctx, h(a) == a, h(h(a)) != a), "unsat")
})

test_that("quantifiers bind their variables", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", I, I)
  x <- z3_int(ctx, "x")
  expect_identical(check_status(ctx, z3_forall(x, f(x) >= x), f(3) < 3), "unsat")
  expect_identical(check_status(ctx, z3_exists(x, f(x) == 7 & x > 100)), "sat")
  # The bound x is distinct from a free x outside the quantifier.
  expect_identical(check_status(ctx, z3_forall(x, f(x) == 0), x == 5, f(x) == 0), "sat")
  expect_identical(check_status(ctx, z3_forall(x, x * 0 == 0)), "sat")
  y <- z3_int(ctx, "y")
  expect_identical(check_status(ctx, !z3_forall(list(x, y), x + y == y + x)), "unsat")
  q <- z3_forall(x, f(x) > 0, patterns = list(list(f(x))))
  expect_identical(z3_sort_kind(q), "bool")
  expect_error(z3_forall(x + 1, x > 0), "constants")
  expect_error(z3_forall(x, x + 1), "Boolean")
  expect_error(z3_forall(list(), x > 0), "at least one")
})

test_that("tactics and goals", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  g <- z3_goal(ctx)
  z3_add(g, x == y + 1, y > 2, x < 10)
  expect_length(z3_assertions(g), 3L)
  t <- z3_tactic_then(z3_tactic(ctx, "simplify"), z3_tactic(ctx, "solve-eqs"))
  sub <- z3_apply_tactic(t, g)
  expect_length(sub, 1L)
  fs <- vapply(z3_goal_formulas(sub[[1]]), format, "")
  expect_false(any(grepl("y", fs)))
  g2 <- z3_goal(ctx)
  z3_add(g2, x > 0, x < 0)
  res <- z3_apply_tactic(z3_tactic(ctx, "smt"), g2)
  expect_identical(z3_goal_status(res[[1]]), "unsat")
  tl <- z3_tactics(ctx)
  expect_true(all(c("simplify", "smt", "solve-eqs") %in% tl$name))
  expect_error(z3_tactic(ctx, "no-such-tactic"), "Z3 error")
  s <- z3_solver_from_tactic(z3_tactic_or_else(z3_tactic(ctx, "smt"), z3_tactic(ctx, "skip")))
  z3_add(s, x > 3)
  expect_identical(z3_check(s), "sat")
  rep <- z3_tactic_repeat(z3_tactic(ctx, "simplify"), 3)
  expect_s3_class(rep, "z3_tactic")
  expect_s3_class(z3_tactic_try_for(rep, 100), "z3_tactic")
  expect_length(z3_apply_tactic(z3_tactic(ctx, "simplify"), g, som = TRUE), 1L)
  expect_output(print(g), "z3_goal")
})
