test_that("z3_check_result records the answer", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x > 2, x < 5)
  r <- z3_check_result(s)
  expect_s3_class(r, "z3_check_result")
  expect_identical(r$status, "sat")
  expect_true(z3_value(r$model$x) %in% 3:4)
  expect_null(r$core)
  expect_match(r$fingerprint, "^[0-9a-f]{16}$")
  expect_identical(z3_check_result(s)$fingerprint, r$fingerprint)
  expect_output(print(r), "z3_check_result: sat")
  z3_assert_and_track(s, x > 10, "big")
  u <- z3_check_result(s)
  expect_identical(u$status, "unsat")
  expect_null(u$model)
  expect_identical(names(u$core), "big")
  expect_false(identical(u$fingerprint, r$fingerprint))
  o <- z3_optimize(ctx)
  z3_add(o, x < 9)
  z3_maximize(o, x)
  ro <- z3_check_result(o)
  expect_identical(ro$status, "sat")
  expect_length(ro$objectives, 1L)
  expect_error(z3_check_result(1), "z3_solver or z3_optimize")
})

test_that("z3_build_info describes the build", {
  b <- z3_build_info()
  expect_true(b$provider %in% c("system", "download"))
  expect_identical(b$z3_runtime, z3_version()$runtime)
  expect_type(b$library, "character")
  if (identical(b$provider, "download")) expect_match(b$sha256, "^[0-9a-f]{64}$")
})

test_that("batch construction, evaluation and lookup", {
  ctx <- z3_context()
  v <- z3_ints(ctx, paste0("v", 1:50))
  expect_named(v, paste0("v", 1:50))
  s <- z3_solver(ctx)
  z3_add(s, Map(function(a, i) a == i, v, seq_along(v)))
  z3_check(s)
  m <- z3_model(s)
  expect_equal(z3_value(m$v7), 7)
  ev <- z3_eval(m, list(a = v$v1, b = v$v2 * 2))
  expect_named(ev, c("a", "b"))
  expect_equal(z3_value(ev$b), 4)
  pv <- z3_model_values(m, list(v$v3, total = v$v1 + v$v2, z3_int(ctx, "free")))
  expect_named(pv, c("v3", "total", "free"))
  expect_equal(unlist(pv), c(v3 = 3, total = 3, free = 0))
  # Adding a constant to a hand-built model refreshes the name index.
  hm <- z3_model(ctx)
  expect_null(hm$k)
  z3_model_set(hm, z3_int(ctx, "k"), 5)
  expect_equal(z3_value(hm$k), 5)
})
