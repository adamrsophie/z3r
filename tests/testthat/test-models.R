test_that("evaluation with and without model completion", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  y <- z3_int(ctx, "y")
  s <- z3_solver(ctx)
  z3_add(s, x == 3)
  z3_check(s)
  m <- z3_model(s)
  expect_identical(format(z3_eval(m, x + 1)), "4")
  expect_identical(format(z3_eval(m, x + y)), "(+ 3 y)")
  expect_identical(z3_sort_kind(z3_eval(m, x + y, completion = TRUE)), "int")
  expect_identical(z3_value(z3_eval(m, x + y, completion = TRUE)), 3)
  expect_identical(z3_value(z3_eval(m, x > 2)), TRUE)
  expect_identical(z3_value(z3_eval(m, 5)), 5)
  expect_error(z3_eval(m, x, completion = NA), "TRUE or FALSE")
})

test_that("model contents keep exact values", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  r <- z3_real(ctx, "r")
  p <- z3_bool(ctx, "p")
  s <- z3_solver(ctx)
  z3_add(s, x == z3_int_val(ctx, "1180591620717411303424"), 3 * r == 1, p)
  z3_check(s)
  m <- z3_model(s)
  l <- as.list(m)
  expect_setequal(names(l), c("x", "r", "p"))
  expect_true(all(vapply(l, z3_is_expr, TRUE)))
  expect_identical(format(l$x), "1180591620717411303424")
  vals <- z3_model_values(m)
  expect_identical(vals$p, TRUE)
  expect_identical(as.character(vals$x), "1180591620717411303424")
  expect_identical(as.character(vals$r), "1/3")
  expect_identical(length(m), 3L)
  expect_output(print(m), "x = 1180591620717411303424")
  expect_match(as.character(m), "x -> 1180591620717411303424")
})

test_that("algebraic model values are kept as expressions", {
  ctx <- z3_context()
  r <- z3_real(ctx, "r")
  s <- z3_solver(ctx)
  z3_add(s, r * r * r == 2)
  z3_check(s)
  vals <- z3_model_values(z3_model(s))
  expect_true(z3_is_expr(vals$r))
  expect_equal(z3_value(vals$r, exact = FALSE), 2^(1 / 3))
})

test_that("models of uninterpreted functions", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx)
  f <- z3_function(ctx, "f", list(I), I)
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, f(1) == 10, f(2) == 20, x == f(1) + f(2))
  z3_check(s)
  m <- z3_model(s)
  expect_identical(z3_value(z3_eval(m, x)), 30)
  expect_identical(z3_value(z3_eval(m, f(2))), 20)
  fs <- z3_model_functions(m)
  expect_named(fs, "f")
  expect_true(all(c("decl", "entries", "else") %in% names(fs$f)))
  expect_output(print(m), "f\\(")
})

test_that("partial models without default values can be printed", {
  z3_global_param_set("model.partial", TRUE)
  on.exit(z3_global_param_set("model.partial", FALSE), add = TRUE)
  ctx <- z3_context()
  f <- z3_function(ctx, "f", z3_int_sort(ctx), z3_int_sort(ctx))
  s <- z3_solver(ctx)
  z3_add(s, f(1) == 5)
  expect_identical(z3_check(s), "sat")
  m <- z3_model(s)
  expect_no_error(format(m))
  fi <- z3_model_functions(m)$f
  expect_length(fi$entries, 1L)
})

test_that("each model handle is a separate copy", {
  ctx <- z3_context()
  x <- z3_int(ctx, "x")
  s <- z3_solver(ctx)
  z3_add(s, x > 5)
  z3_check(s)
  m1 <- z3_model(s)
  m2 <- z3_model(s)
  z3_model_set(m1, x, 42)
  expect_identical(z3_value(z3_eval(m1, x)), 42)
  expect_false(identical(z3_value(z3_eval(m2, x)), 42))
  expect_true(z3_value(z3_eval(z3_model(s), x > 5)))
  o <- z3_optimize(ctx)
  z3_add(o, x > 5)
  z3_check(o)
  z3_model_set(z3_model(o), x, 0)
  expect_true(z3_value(z3_eval(z3_model(o), x > 5)))
})

test_that("printing a model shows each overloaded function", {
  ctx <- z3_context()
  I <- z3_int_sort(ctx); B <- z3_bool_sort(ctx)
  fi <- z3_function(ctx, "f", list(I), I)
  fb <- z3_function(ctx, "f", list(B), B)
  s <- z3_solver(ctx)
  z3_add(s, fi(1) == 7, fb(TRUE))
  z3_check(s)
  out <- format(z3_model(s))
  expect_true(any(grepl("7", out)))
  expect_true(any(grepl("true", out)))
})
